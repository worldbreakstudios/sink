export interface TablePolicyHooks<TAuthContext = unknown> {
  readScope?: (
    context: SyncQueryPolicyContext<unknown, TAuthContext>,
  ) => MaybePromise<SyncWhereClause[]>
  authorize?: (
    context:
      | SyncQueryPolicyContext<unknown, TAuthContext>
      | SyncMutationPolicyContext<unknown, unknown, TAuthContext>,
  ) => MaybePromise<boolean | void>
  validateInput?: (
    context: SyncMutationPolicyContext<unknown, unknown, TAuthContext>,
  ) => MaybePromise<void>
  validateExisting?: (
    context: SyncMutationPolicyContext<unknown, unknown, TAuthContext>,
  ) => MaybePromise<void>
  transformInput?: (
    context: SyncMutationPolicyContext<unknown, unknown, TAuthContext> & {
      input: Record<string, unknown>
    },
  ) => MaybePromise<Record<string, unknown>>
  afterCommit?: (
    context: SyncMutationPolicyContext<unknown, unknown, TAuthContext> & {
      result: unknown
    },
  ) => MaybePromise<void>
}

