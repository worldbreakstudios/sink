export function collectDefinedQueries(
  modules: Array<Record<string, unknown>>,
): Record<string, SyncQueryDefinition<any, any, any, any>> {
  const queries: Record<string, SyncQueryDefinition<any, any, any, any>> = {}

  for (const moduleExports of modules) {
    for (const value of Object.values(moduleExports)) {
      if (
        value &&
        typeof value === 'object' &&
        (value as { __sinkDefinitionType?: string }).__sinkDefinitionType === 'query'
      ) {
        const definition = value as SyncQueryDefinition<any, any>

        if (queries[definition.name]) {
          throw new Error(`Duplicate query definition "${definition.name}".`)
        }

        queries[definition.name] = definition
      }
    }
  }

  return queries
}

export function collectDefinedMutations(
  modules: Array<Record<string, unknown>>,
): Record<string, SyncMutationDefinition<any, any, any, any, any>> {
  const mutations: Record<
    string,
    SyncMutationDefinition<any, any, any, any, any>
  > = {}

  for (const moduleExports of modules) {
    for (const value of Object.values(moduleExports)) {
      if (
        value &&
        typeof value === 'object' &&
        (value as { __sinkDefinitionType?: string }).__sinkDefinitionType === 'mutation'
      ) {
        const definition = value as SyncMutationDefinition<any, any, any>

        if (mutations[definition.name]) {
          throw new Error(`Duplicate mutation definition "${definition.name}".`)
        }

        mutations[definition.name] = definition
      }
    }
  }

  return mutations
}

export function collectDefinedPolicies(
  modules: Array<Record<string, unknown>>,
): Record<string, TablePolicyHooks<any> | undefined> {
  const policies: Record<string, TablePolicyHooks<any> | undefined> = {}

  for (const moduleExports of modules) {
    for (const value of Object.values(moduleExports)) {
      if (
        value &&
        typeof value === 'object' &&
        (value as { __sinkDefinitionType?: string }).__sinkDefinitionType === 'table-policy'
      ) {
        const definition = value as TablePoliciesDefinition

        if (policies[definition.tableName]) {
          throw new Error(
            `Duplicate table policy definition for "${definition.tableName}".`,
          )
        }

        policies[definition.tableName] = definition.hooks
      }
    }
  }

  return policies
}

export function mergeSyncOperationRegistry(
  generated: SyncOperationRegistry<any>,
  custom: {
    queries?: Record<string, SyncQueryDefinition<any, any, any, any>>
    mutations?: Record<string, SyncMutationDefinition<any, any, any, any, any>>
    policies?: Record<string, TablePolicyHooks<any> | undefined>
  },
): SyncOperationRegistry<any> {
  const queries = { ...generated.queries }
  const mutations = { ...generated.mutations }
  const policies = { ...generated.policies, ...custom.policies }

  for (const [name, query] of Object.entries(custom.queries ?? {})) {
    if (queries[name]) {
      throw new Error(`Duplicate query definition "${name}".`)
    }

    queries[name] = query
  }

  for (const [name, mutation] of Object.entries(custom.mutations ?? {})) {
    if (mutations[name]) {
      throw new Error(`Duplicate mutation definition "${name}".`)
    }

    mutations[name] = mutation
  }

  return {
    queries,
    mutations,
    policies,
  }
}
