export function emitServer(clientImportPath: string): string {
  const lines: string[] = []

  lines.push('// Auto-generated by `sink generate` — do not edit manually.')
  lines.push('')
  lines.push(
    "import type { AsyncSqliteDatabase, SqliteMutationEvent } from '@sink/lib'",
  )
  lines.push(
    "import type { CreateNodeSqliteSyncServerOptions } from '@sink/lib/server'",
  )
  lines.push(
    "import { createNodeSqliteSyncServer, ensureSqliteSyncServerTables } from '@sink/lib/server'",
  )
  lines.push(
    `import { SCHEMA_HASH, SCHEMA_VALIDATOR_DESCRIPTORS, SYNC_SCHEMA, createAllTables } from '${clientImportPath}'`,
  )
  lines.push('')
  lines.push('export { SCHEMA_HASH, SCHEMA_VALIDATOR_DESCRIPTORS, SYNC_SCHEMA }')
  lines.push('')
  lines.push('export type SyncMutationEvent = SqliteMutationEvent')
  lines.push('')
  lines.push('export const SCHEMA_SERVER_META = {')
  lines.push('  schemaHash: SCHEMA_HASH,')
  lines.push('  schema: SYNC_SCHEMA,')
  lines.push('  validators: SCHEMA_VALIDATOR_DESCRIPTORS,')
  lines.push('} as const')
  lines.push('')
  lines.push(
    'export async function createServerTables(db: AsyncSqliteDatabase): Promise<void> {',
  )
  lines.push('  await createAllTables(db)')
  lines.push('  await ensureSqliteSyncServerTables(db)')
  lines.push('}')
  lines.push('')
  lines.push('export async function createGeneratedSyncServer(')
  lines.push(
    "  options: Omit<CreateNodeSqliteSyncServerOptions, 'schema'>,",
  )
  lines.push(') {')
  lines.push('  await createServerTables(options.database)')
  lines.push('  return createNodeSqliteSyncServer({')
  lines.push('    ...options,')
  lines.push('    schema: SYNC_SCHEMA,')
  lines.push('  })')
  lines.push('}')

  return lines.join('\n')
}
