import type { ColumnDescriptor, TableDefinition } from '@sink/lib'

export function emit(definitions: TableDefinition[]): string {
  const lines: string[] = []

  lines.push('// Auto-generated by `sink generate` — do not edit manually.')
  lines.push('')
  lines.push("import type { TransactionConfig } from '@tanstack/db'")
  lines.push("import { createTransaction } from '@tanstack/db'")
  lines.push(
    "import type { AsyncSqliteDatabase, SqliteCollection, SqliteIndexDefinition, SqliteReferenceColumn } from '@sink/lib'",
  )
  lines.push("import { createSqliteCollection } from '@sink/lib'")
  lines.push('')
  lines.push(
    "export type Id<TTableName extends string> = string & { readonly __tableName: TTableName }",
  )
  lines.push('')
  lines.push('function createId<TTableName extends string>(): Id<TTableName> {')
  lines.push('  const cryptoApi = globalThis.crypto')
  lines.push('')
  lines.push('  if (!cryptoApi?.getRandomValues) {')
  lines.push("    throw new Error('crypto.getRandomValues() is not available in this environment.')")
  lines.push('  }')
  lines.push('')
  lines.push('  const bytes = cryptoApi.getRandomValues(new Uint8Array(16))')
  lines.push(
    "  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('') as Id<TTableName>",
  )
  lines.push('}')
  lines.push('')
  lines.push('function currentTimestamp(): bigint {')
  lines.push('  return BigInt(Date.now())')
  lines.push('}')
  lines.push('')

  // Row type interfaces
  for (const def of definitions) {
    lines.push(`export interface ${rowTypeName(def.tableName)} {`)
    lines.push(`  _id: ${systemIdTsType(def.tableName)}`)
    for (const field of getImplicitSystemFields(def)) {
      lines.push(`  ${field.name}: ${field.tsType}`)
    }
    for (const [colName, col] of Object.entries(def.columns)) {
      lines.push(`  ${colName}: ${renderTsType(col)}`)
    }
    lines.push('}')
    lines.push('')
  }

  // AnyRow union
  const rowTypes = definitions.map((d) => rowTypeName(d.tableName))
  lines.push(`export type AnyRow = ${rowTypes.join(' | ')}`)
  lines.push('')

  // SQL CREATE TABLE constants
  for (const def of definitions) {
    const constName = `SQL_CREATE_${def.tableName.toUpperCase()}`
    lines.push(`export const ${constName} = \`CREATE TABLE IF NOT EXISTS "${def.tableName}" (`)
    const colDefs: string[] = ['  "_id" TEXT PRIMARY KEY']
    for (const field of getImplicitSystemFields(def)) {
      colDefs.push(`  "${field.name}" ${field.sqliteType}`)
    }
    for (const [colName, col] of Object.entries(def.columns)) {
      let colDef = `  "${colName}" ${col.sqliteType}`
      if (col.defaultValue !== undefined) {
        colDef += ` DEFAULT ${sqlLiteral(col.defaultValue)}`
      }
      colDefs.push(colDef)
    }
    lines.push(colDefs.join(',\n'))
    lines.push(');\`')
    lines.push('')
  }

  // SQL_CREATE_ALL array
  const createConsts = definitions.map(
    (d) => `SQL_CREATE_${d.tableName.toUpperCase()}`,
  )
  lines.push(
    `export const SQL_CREATE_ALL = [${createConsts.join(', ')}] as const`,
  )
  lines.push('')
  lines.push(
    `export const SQL_CREATE_INDEXES = ${renderStringArray(
      definitions.flatMap((def) =>
        getGeneratedIndexes(def)
          .filter((index) => index.createSql !== null)
          .map((index) => index.createSql as string),
      ),
    )} as const`,
  )
  lines.push('')

  // createAllTables function
  lines.push(
    'export async function createAllTables(db: AsyncSqliteDatabase): Promise<void> {',
  )
  lines.push('  for (const sql of SQL_CREATE_ALL) {')
  lines.push('    await db.execute(sql)')
  lines.push('  }')
  lines.push('  for (const sql of SQL_CREATE_INDEXES) {')
  lines.push('    await db.execute(sql)')
  lines.push('  }')
  lines.push('}')
  lines.push('')

  // TableName union
  const tableNames = definitions.map((d) => `'${d.tableName}'`)
  lines.push(`export type TableName = ${tableNames.join(' | ')}`)
  lines.push('')
  lines.push("declare module '@sink/lib' {")
  lines.push('  interface RegisteredSchemaTables {')
  for (const def of definitions) {
    lines.push(`    '${def.tableName}': true`)
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')
  lines.push('export type ReferenceColumns = Record<')
  lines.push('  TableName,')
  lines.push("  Partial<Record<string, SqliteReferenceColumn>>")
  lines.push('>')
  lines.push('')
  lines.push('export const REFERENCE_COLUMNS: ReferenceColumns = {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: {`)
    for (const [columnName, col] of Object.entries(def.columns)) {
      if (col.referencedTable !== undefined) {
        lines.push(
          `    ${columnName}: { referencedTable: '${col.referencedTable}', enforceExists: ${col.enforceExists} },`,
        )
      }
    }
    lines.push('  },')
  }
  lines.push('}')
  lines.push('')
  lines.push('export type IndexesByTable = {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: Record<string, SqliteIndexDefinition<readonly string[]>>`,
    )
  }
  lines.push('}')
  lines.push('')
  lines.push('export const INDEXES = {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: {`)
    for (const index of getGeneratedIndexes(def)) {
      lines.push(
        `    ${index.name}: { fields: ${renderStringTuple(index.fields)}, unique: ${index.unique} },`,
      )
    }
    lines.push('  },')
  }
  lines.push('} as const satisfies IndexesByTable')
  lines.push('')

  // SchemaCollections interface
  lines.push('export interface SchemaCollections {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: SqliteCollection<${rowTypeName(def.tableName)}, ${systemIdTsType(def.tableName)}, typeof INDEXES.${def.tableName}>`,
    )
  }
  lines.push('}')
  lines.push('')

  // createCollections function
  lines.push(
    'export async function createCollections(db: AsyncSqliteDatabase): Promise<SchemaCollections> {',
  )
  lines.push('  return {')
  for (const def of definitions) {
    lines.push(
      `    ${def.tableName}: await createSqliteCollection<${rowTypeName(def.tableName)}, ${systemIdTsType(def.tableName)}, typeof INDEXES.${def.tableName}>({`,
    )
    lines.push(`      id: 'sqlite-${def.tableName}',`)
    lines.push(`      tableName: '${def.tableName}',`)
    lines.push(`      keyColumn: '_id',`)
    lines.push(`      getKey: (row) => row._id,`)
    lines.push(`      database: db,`)
    lines.push(`      indexes: INDEXES.${def.tableName},`)
    lines.push(`      referenceColumns: REFERENCE_COLUMNS.${def.tableName},`)
    lines.push('    }),')
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')

  // createBatchTransaction helper
  lines.push('export function createBatchTransaction(')
  lines.push('  collections: SchemaCollections,')
  lines.push("  config?: Omit<TransactionConfig<AnyRow>, 'mutationFn'>,")
  lines.push(') {')
  lines.push('  return createTransaction<AnyRow>({')
  lines.push('    ...config,')
  lines.push('    mutationFn: async ({ transaction }) => {')
  for (const def of definitions) {
    lines.push(
      `      await collections.${def.tableName}.utils.persistMutations(transaction)`,
    )
  }
  lines.push('    },')
  lines.push('  })')
  lines.push('}')
  lines.push('')

  // Per-table CRUD helpers
  for (const def of definitions) {
    const rowType = rowTypeName(def.tableName)
    const singular = singularize(def.tableName)
    const plural = def.tableName
    const rowIdType = systemIdTsType(def.tableName)
    const insertInputType = renderInsertInputType(def, rowType)
    const insertSystemFields = getInsertSystemFieldEntries(def, 'row')

    // insertX (single)
    lines.push(
      `export function insert${pascal(singular)}(collections: SchemaCollections, row: ${insertInputType}) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(
      `    const completeRow = { ${insertSystemFields.join(', ')}, ...row } as ${rowType}`,
    )
    lines.push(
      `    collections.${def.tableName}.insert(completeRow)`,
    )
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // updateX (single)
    lines.push(
      `export function update${pascal(singular)}(collections: SchemaCollections, _id: ${rowIdType}, changes: Partial<Omit<${rowType}, '_id'>>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(
      `    collections.${def.tableName}.update(_id, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'changes')}) })`,
    )
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // deleteX (single)
    lines.push(
      `export function delete${pascal(singular)}(collections: SchemaCollections, _id: ${rowIdType}) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(`    collections.${def.tableName}.delete(_id)`)
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // insertXs (batch)
    lines.push(
      `export function insert${pascal(plural)}(collections: SchemaCollections, rows: Array<${insertInputType}>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const row of rows) {')
    lines.push(
      `      const completeRow = { ${insertSystemFields.join(', ')}, ...row } as ${rowType}`,
    )
    lines.push(
      `      collections.${def.tableName}.insert(completeRow)`,
    )
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // updateXs (batch)
    lines.push(
      `export function update${pascal(plural)}(collections: SchemaCollections, updates: Array<{ _id: ${rowIdType}; changes: Partial<Omit<${rowType}, '_id'>> }>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const u of updates) {')
    lines.push(
      `      collections.${def.tableName}.update(u._id, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'u.changes')}) })`,
    )
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // deleteXs (batch)
    lines.push(
      `export function delete${pascal(plural)}(collections: SchemaCollections, ids: ${rowIdType}[]) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const _id of ids) {')
    lines.push(`      collections.${def.tableName}.delete(_id)`)
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')
  }

  return lines.join('\n')
}

function rowTypeName(tableName: string): string {
  return pascal(singularize(tableName)) + 'Row'
}

function pascal(str: string): string {
  return str
    .split(/[_-]/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('')
}

function singularize(name: string): string {
  if (name.endsWith('ies')) {
    return name.slice(0, -3) + 'y'
  }
  if (name.endsWith('ses') || name.endsWith('xes') || name.endsWith('zes')) {
    return name.slice(0, -2)
  }
  if (name.endsWith('s') && !name.endsWith('ss')) {
    return name.slice(0, -1)
  }
  return name
}

function sqlLiteral(value: unknown): string {
  if (typeof value === 'string') {
    return `'${value.replace(/'/g, "''")}'`
  }
  if (typeof value === 'bigint') {
    return value.toString()
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }
  return 'NULL'
}

function renderTsType(col: ColumnDescriptor): string {
  if (col.referencedTable !== undefined) {
    return col.isNullable
      ? `Id<'${col.referencedTable}'> | null`
      : `Id<'${col.referencedTable}'>`
  }

  return col.tsType
}

function systemIdTsType(tableName: string): string {
  return `Id<'${tableName}'>`
}

function getImplicitSystemFields(def: TableDefinition): Array<{
  name: string
  tsType: string
  sqliteType: string
}> {
  const fields: Array<{ name: string; tsType: string; sqliteType: string }> = []

  if (def.options.withCreatedAt) {
    fields.push({
      name: '_createdAt',
      tsType: 'bigint',
      sqliteType: 'INTEGER NOT NULL',
    })
  }

  if (def.options.withUpdatedAt) {
    fields.push({
      name: '_updatedAt',
      tsType: 'bigint',
      sqliteType: 'INTEGER NOT NULL',
    })
  }

  if (def.options.withArchivedAt) {
    fields.push({
      name: '_archivedAt',
      tsType: 'bigint | null',
      sqliteType: 'INTEGER',
    })
  }

  return fields
}

function getInsertSystemFieldEntries(def: TableDefinition, sourceName: string): string[] {
  const fields = [`_id: createId<'${def.tableName}'>()`]

  if (def.options.withCreatedAt) {
    fields.push(`_createdAt: ${sourceName}._createdAt ?? currentTimestamp()`)
  }

  if (def.options.withUpdatedAt) {
    fields.push(`_updatedAt: ${sourceName}._updatedAt ?? currentTimestamp()`)
  }

  if (def.options.withArchivedAt) {
    fields.push(`_archivedAt: ${sourceName}._archivedAt ?? null`)
  }

  return fields
}

function renderInsertInputType(def: TableDefinition, rowType: string): string {
  const systemFieldNames = getImplicitSystemFields(def).map((field) => `'${field.name}'`)

  if (systemFieldNames.length === 0) {
    return `Omit<${rowType}, '_id'>`
  }

  const systemFieldsUnion = systemFieldNames.join(' | ')
  return `Omit<${rowType}, '_id' | ${systemFieldsUnion}> & Partial<Pick<${rowType}, ${systemFieldsUnion}>>`
}

function renderUpdateAssignment(def: TableDefinition, sourceName: string): string {
  if (!def.options.withUpdatedAt) {
    return sourceName
  }

  return `{ ...${sourceName}, _updatedAt: ${sourceName}._updatedAt ?? currentTimestamp() }`
}

function getGeneratedIndexes(def: TableDefinition): Array<{
  name: string
  fields: readonly string[]
  unique: boolean
  createSql: string | null
}> {
  const indexes: Array<{
    name: string
    fields: readonly string[]
    unique: boolean
    createSql: string | null
  }> = [
    {
      name: 'by_id',
      fields: ['_id'],
      unique: true,
      createSql: null,
    },
  ]

  if (def.options.withCreatedAt) {
    indexes.push({
      name: 'by_creation_time',
      fields: ['_createdAt', '_id'],
      unique: false,
      createSql: createIndexSql(
        def.tableName,
        'by_creation_time',
        ['_createdAt', '_id'],
        false,
      ),
    })
  }

  for (const index of def.indexes) {
    const tieBreaker = def.options.withCreatedAt ? '_createdAt' : '_id'
    const indexFields = index.unique
      ? [...index.fields]
      : [...index.fields, tieBreaker]
    indexes.push({
      name: index.name,
      fields: indexFields,
      unique: index.unique,
      createSql: createIndexSql(
        def.tableName,
        index.name,
        indexFields,
        index.unique,
      ),
    })
  }

  return indexes
}

function createIndexSql(
  tableName: string,
  indexName: string,
  fields: readonly string[],
  unique: boolean,
): string {
  const expressions = fields.map(fieldPathToSqlExpression)
  return `CREATE ${unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS "${escapeSqlIdentifier(`idx_${tableName}_${indexName}`)}" ON "${escapeSqlIdentifier(tableName)}" (${expressions.join(', ')});`
}

function fieldPathToSqlExpression(fieldPath: string): string {
  if (!fieldPath.includes('.')) {
    return `"${escapeSqlIdentifier(fieldPath)}"`
  }

  const [root, ...segments] = fieldPath.split('.')
  const jsonPath = `$.${segments.join('.')}`
  if (!root) {
    throw new Error(`Invalid field path "${fieldPath}".`)
  }
  return `json_extract("${escapeSqlIdentifier(root)}", '${jsonPath.replace(/'/g, "''")}')`
}

function escapeSqlIdentifier(identifier: string): string {
  return identifier.replace(/"/g, '""')
}

function renderStringTuple(fields: readonly string[]): string {
  return `[${fields.map((field) => `'${field}'`).join(', ')}] as const`
}

function renderStringArray(values: readonly string[]): string {
  return `[${values.map((value) => `\`${value.replace(/`/g, '\\`')}\``).join(', ')}]`
}
