import type { ColumnDescriptor, TableDefinition } from '@sink/lib'

export function emit(definitions: TableDefinition[]): string {
  const lines: string[] = []

  lines.push('// Auto-generated by `sink generate` — do not edit manually.')
  lines.push('')
  lines.push("import type { TransactionConfig } from '@tanstack/db'")
  lines.push("import { createTransaction } from '@tanstack/db'")
  lines.push(
    "import type { FrontendSqliteDatabase, SqliteCollection } from '@sink/lib'",
  )
  lines.push("import { createSqliteCollection } from '@sink/lib'")
  lines.push('')
  lines.push(
    "export type Id<TTableName extends string> = string & { readonly __tableName: TTableName }",
  )
  lines.push('')
  lines.push('function createId<TTableName extends string>(): Id<TTableName> {')
  lines.push('  const cryptoApi = globalThis.crypto')
  lines.push('')
  lines.push('  if (!cryptoApi?.getRandomValues) {')
  lines.push("    throw new Error('crypto.getRandomValues() is not available in this environment.')")
  lines.push('  }')
  lines.push('')
  lines.push('  const bytes = cryptoApi.getRandomValues(new Uint8Array(16))')
  lines.push(
    "  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('') as Id<TTableName>",
  )
  lines.push('}')
  lines.push('')

  // Row type interfaces
  for (const def of definitions) {
    lines.push(`export interface ${rowTypeName(def.tableName)} {`)
    lines.push(`  _id: ${systemIdTsType(def.tableName)}`)
    for (const [colName, col] of Object.entries(def.columns)) {
      lines.push(`  ${colName}: ${renderTsType(col)}`)
    }
    lines.push('}')
    lines.push('')
  }

  // AnyRow union
  const rowTypes = definitions.map((d) => rowTypeName(d.tableName))
  lines.push(`export type AnyRow = ${rowTypes.join(' | ')}`)
  lines.push('')

  // SQL CREATE TABLE constants
  for (const def of definitions) {
    const constName = `SQL_CREATE_${def.tableName.toUpperCase()}`
    lines.push(`export const ${constName} = \`CREATE TABLE IF NOT EXISTS "${def.tableName}" (`)
    const colDefs: string[] = ['  "_id" TEXT PRIMARY KEY']
    for (const [colName, col] of Object.entries(def.columns)) {
      let colDef = `  "${colName}" ${col.sqliteType}`
      if (col.defaultValue !== undefined) {
        colDef += ` DEFAULT ${sqlLiteral(col.defaultValue)}`
      }
      colDefs.push(colDef)
    }
    lines.push(colDefs.join(',\n'))
    lines.push(');\`')
    lines.push('')
  }

  // SQL_CREATE_ALL array
  const createConsts = definitions.map(
    (d) => `SQL_CREATE_${d.tableName.toUpperCase()}`,
  )
  lines.push(
    `export const SQL_CREATE_ALL = [${createConsts.join(', ')}] as const`,
  )
  lines.push('')

  // createAllTables function
  lines.push(
    'export function createAllTables(db: FrontendSqliteDatabase): void {',
  )
  lines.push('  for (const sql of SQL_CREATE_ALL) {')
  lines.push('    db.execute(sql)')
  lines.push('  }')
  lines.push('}')
  lines.push('')

  // TableName union
  const tableNames = definitions.map((d) => `'${d.tableName}'`)
  lines.push(`export type TableName = ${tableNames.join(' | ')}`)
  lines.push('')
  lines.push("declare module '@sink/lib' {")
  lines.push('  interface RegisteredSchemaTables {')
  for (const def of definitions) {
    lines.push(`    '${def.tableName}': true`)
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')

  // SchemaCollections interface
  lines.push('export interface SchemaCollections {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: SqliteCollection<${rowTypeName(def.tableName)}, ${systemIdTsType(def.tableName)}>`,
    )
  }
  lines.push('}')
  lines.push('')

  // createCollections function
  lines.push(
    'export function createCollections(db: FrontendSqliteDatabase): SchemaCollections {',
  )
  lines.push('  return {')
  for (const def of definitions) {
    const orderBy = def.options.orderBy
    lines.push(
      `    ${def.tableName}: createSqliteCollection<${rowTypeName(def.tableName)}, ${systemIdTsType(def.tableName)}>({`,
    )
    lines.push(`      id: 'sqlite-${def.tableName}',`)
    lines.push(`      tableName: '${def.tableName}',`)
    lines.push(`      keyColumn: '_id',`)
    lines.push(`      getKey: (row) => row._id,`)
    lines.push(`      database: db,`)
    if (orderBy) {
      lines.push(`      orderBy: '${orderBy}',`)
    }
    lines.push('    }),')
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')

  // createBatchTransaction helper
  lines.push('export function createBatchTransaction(')
  lines.push('  collections: SchemaCollections,')
  lines.push("  config?: Omit<TransactionConfig<AnyRow>, 'mutationFn'>,")
  lines.push(') {')
  lines.push('  return createTransaction<AnyRow>({')
  lines.push('    ...config,')
  lines.push('    mutationFn: async ({ transaction }) => {')
  for (const def of definitions) {
    lines.push(
      `      await collections.${def.tableName}.utils.persistMutations(transaction)`,
    )
  }
  lines.push('    },')
  lines.push('  })')
  lines.push('}')
  lines.push('')

  // Per-table CRUD helpers
  for (const def of definitions) {
    const rowType = rowTypeName(def.tableName)
    const singular = singularize(def.tableName)
    const plural = def.tableName
    const rowIdType = systemIdTsType(def.tableName)

    // insertX (single)
    lines.push(
      `export function insert${pascal(singular)}(collections: SchemaCollections, row: Omit<${rowType}, '_id'>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(
      `    const completeRow = { _id: createId<'${def.tableName}'>(), ...row } as ${rowType}`,
    )
    lines.push(
      `    collections.${def.tableName}.insert(completeRow)`,
    )
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // updateX (single)
    lines.push(
      `export function update${pascal(singular)}(collections: SchemaCollections, _id: ${rowIdType}, changes: Partial<Omit<${rowType}, '_id'>>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(
      `    collections.${def.tableName}.update(_id, (draft) => { Object.assign(draft, changes) })`,
    )
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // deleteX (single)
    lines.push(
      `export function delete${pascal(singular)}(collections: SchemaCollections, _id: ${rowIdType}) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(`    collections.${def.tableName}.delete(_id)`)
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // insertXs (batch)
    lines.push(
      `export function insert${pascal(plural)}(collections: SchemaCollections, rows: Omit<${rowType}, '_id'>[]) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const row of rows) {')
    lines.push(
      `      const completeRow = { _id: createId<'${def.tableName}'>(), ...row } as ${rowType}`,
    )
    lines.push(
      `      collections.${def.tableName}.insert(completeRow)`,
    )
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // updateXs (batch)
    lines.push(
      `export function update${pascal(plural)}(collections: SchemaCollections, updates: Array<{ _id: ${rowIdType}; changes: Partial<Omit<${rowType}, '_id'>> }>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const u of updates) {')
    lines.push(
      `      collections.${def.tableName}.update(u._id, (draft) => { Object.assign(draft, u.changes) })`,
    )
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    // deleteXs (batch)
    lines.push(
      `export function delete${pascal(plural)}(collections: SchemaCollections, ids: ${rowIdType}[]) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const _id of ids) {')
    lines.push(`      collections.${def.tableName}.delete(_id)`)
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')
  }

  return lines.join('\n')
}

function rowTypeName(tableName: string): string {
  return pascal(singularize(tableName)) + 'Row'
}

function pascal(str: string): string {
  return str
    .split(/[_-]/)
    .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
    .join('')
}

function singularize(name: string): string {
  if (name.endsWith('ies')) {
    return name.slice(0, -3) + 'y'
  }
  if (name.endsWith('ses') || name.endsWith('xes') || name.endsWith('zes')) {
    return name.slice(0, -2)
  }
  if (name.endsWith('s') && !name.endsWith('ss')) {
    return name.slice(0, -1)
  }
  return name
}

function sqlLiteral(value: unknown): string {
  if (typeof value === 'string') {
    return `'${value.replace(/'/g, "''")}'`
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }
  return 'NULL'
}

function renderTsType(col: ColumnDescriptor): string {
  if (col.referencedTable !== undefined) {
    return col.isNullable
      ? `Id<'${col.referencedTable}'> | null`
      : `Id<'${col.referencedTable}'>`
  }

  return col.tsType
}

function systemIdTsType(tableName: string): string {
  return `Id<'${tableName}'>`
}
