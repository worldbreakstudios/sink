import { createHash } from 'node:crypto'
import {
  getPrimaryKeyColumns,
  tableHasActorId,
  tableUsesAutogeneratedId,
  tableUsesActorPrimaryKey,
  type ColumnDescriptor,
  type ColumnValidatorDescriptor,
  type TableDefinition,
} from '@sink/lib'

export function emit(definitions: TableDefinition[]): string {
  const lines: string[] = []
  const definitionsByName = new Map(
    definitions.map((definition) => [definition.tableName, definition]),
  )
  const schemaHash = hashDefinitions(definitions)

  lines.push('// Auto-generated by `sink generate` — do not edit manually.')
  lines.push('')
  lines.push("import type { TransactionConfig } from '@tanstack/db'")
  lines.push("import { createTransaction } from '@tanstack/db'")
  lines.push(
    "import type { AsyncSqliteDatabase, ColumnValidatorDescriptor, SqliteCollection, SqliteIndexDefinition, SqliteReferenceColumn } from '@sink/lib'",
  )
  lines.push("import { createSqliteCollection } from '@sink/lib'")
  lines.push('')
  lines.push(`export const SCHEMA_HASH = '${schemaHash}'`)
  lines.push('')
  lines.push(
    "export type Id<TTableName extends string> = string & { readonly __tableName: TTableName }",
  )
  lines.push('')
  lines.push('function createId<TTableName extends string>(): Id<TTableName> {')
  lines.push('  const cryptoApi = globalThis.crypto')
  lines.push('')
  lines.push('  if (!cryptoApi?.getRandomValues) {')
  lines.push("    throw new Error('crypto.getRandomValues() is not available in this environment.')")
  lines.push('  }')
  lines.push('')
  lines.push('  const bytes = cryptoApi.getRandomValues(new Uint8Array(16))')
  lines.push(
    "  return Array.from(bytes, (byte) => byte.toString(16).padStart(2, '0')).join('') as Id<TTableName>",
  )
  lines.push('}')
  lines.push('')
  lines.push('function currentTimestamp(): bigint {')
  lines.push('  return BigInt(Date.now())')
  lines.push('}')
  lines.push('')

  const tableNames = definitions.map((definition) => `'${definition.tableName}'`)
  lines.push(`export type TableName = ${tableNames.join(' | ')}`)
  lines.push('')

  for (const def of definitions) {
    lines.push(`export interface ${rowTypeName(def.tableName)} {`)
    lines.push(`  _id: ${systemIdTsType(def.tableName)}`)
    for (const field of getImplicitSystemFields(def)) {
      lines.push(`  ${field.name}: ${field.tsType}`)
    }
    for (const [columnName, column] of Object.entries(def.columns)) {
      lines.push(`  ${columnName}: ${renderTsType(column)}`)
    }
    lines.push('}')
    lines.push('')
  }

  for (const def of definitions) {
    const keyType = keyTypeName(def.tableName)

    if (tableUsesActorPrimaryKey(def.options)) {
      lines.push(`export interface ${keyType} {`)
      lines.push(`  _actor: Id<'actors'>`)
      lines.push(`  _id: ${systemIdTsType(def.tableName)}`)
      lines.push('}')
    } else {
      lines.push(`export type ${keyType} = ${systemIdTsType(def.tableName)}`)
    }

    lines.push('')
  }

  const rowTypes = definitions.map((definition) => rowTypeName(definition.tableName))
  lines.push(`export type AnyRow = ${rowTypes.join(' | ')}`)
  lines.push('')
  lines.push('export interface KeyByTable {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: ${keyTypeName(def.tableName)}`)
  }
  lines.push('}')
  lines.push('')
  lines.push('export type AnyKey = KeyByTable[TableName]')
  lines.push('')

  lines.push('export type KeyColumnsByTable = {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: ${renderStringTupleType(getPrimaryKeyColumns(def.options))}`,
    )
  }
  lines.push('}')
  lines.push('')
  lines.push('export const KEY_COLUMNS = {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: ${renderStringTuple(getPrimaryKeyColumns(def.options))},`,
    )
  }
  lines.push('} as const satisfies KeyColumnsByTable')
  lines.push('')

  lines.push('export type IdAutogeneratedByTable = {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: boolean`)
  }
  lines.push('}')
  lines.push('')
  lines.push('export const ID_AUTOGENERATED = {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: ${tableUsesAutogeneratedId(def.options)},`,
    )
  }
  lines.push('} as const satisfies IdAutogeneratedByTable')
  lines.push('')

  for (const def of definitions) {
    const constName = `SQL_CREATE_${def.tableName.toUpperCase()}`
    const primaryKeyColumns = getPrimaryKeyColumns(def.options)
    const columnDefinitions: string[] = []

    if (tableUsesActorPrimaryKey(def.options)) {
      columnDefinitions.push('  "_id" TEXT NOT NULL')
    } else {
      columnDefinitions.push('  "_id" TEXT PRIMARY KEY')
    }

    for (const field of getImplicitSystemFields(def)) {
      columnDefinitions.push(`  "${field.name}" ${field.sqliteType}`)
    }

    for (const [columnName, column] of Object.entries(def.columns)) {
      let columnDefinition = `  "${columnName}" ${column.sqliteType}`

      if (column.defaultValue !== undefined) {
        columnDefinition += ` DEFAULT ${sqlLiteral(column.defaultValue)}`
      }

      columnDefinitions.push(columnDefinition)
    }

    if (tableUsesActorPrimaryKey(def.options)) {
      columnDefinitions.push(
        `  PRIMARY KEY (${primaryKeyColumns
          .map((columnName) => `"${columnName}"`)
          .join(', ')})`,
      )
    }

    lines.push(
      `export const ${constName} = \`CREATE TABLE IF NOT EXISTS "${def.tableName}" (`,
    )
    lines.push(columnDefinitions.join(',\n'))
    lines.push(');\`')
    lines.push('')
  }

  const createConstants = definitions.map(
    (definition) => `SQL_CREATE_${definition.tableName.toUpperCase()}`,
  )
  lines.push(
    `export const SQL_CREATE_ALL = [${createConstants.join(', ')}] as const`,
  )
  lines.push('')
  lines.push(
    `export const SQL_CREATE_INDEXES = ${renderStringArray(
      definitions.flatMap((definition) =>
        getGeneratedIndexes(definition)
          .filter((index) => index.createSql !== null)
          .map((index) => index.createSql as string),
      ),
    )} as const`,
  )
  lines.push('')

  lines.push(
    'export async function createAllTables(db: AsyncSqliteDatabase): Promise<void> {',
  )
  lines.push('  for (const sql of SQL_CREATE_ALL) {')
  lines.push('    await db.execute(sql)')
  lines.push('  }')
  lines.push('  for (const sql of SQL_CREATE_INDEXES) {')
  lines.push('    await db.execute(sql)')
  lines.push('  }')
  lines.push('}')
  lines.push('')

  lines.push("declare module '@sink/lib' {")
  lines.push('  interface RegisteredSchemaTables {')
  for (const def of definitions) {
    lines.push(`    '${def.tableName}': true`)
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')

  lines.push('export type ReferenceColumns = Record<')
  lines.push('  TableName,')
  lines.push("  Partial<Record<string, SqliteReferenceColumn>>")
  lines.push('>')
  lines.push('')
  lines.push('export const REFERENCE_COLUMNS: ReferenceColumns = {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: {`)

    if (tableHasActorId(def.options)) {
      lines.push(
        "    _actor: { referencedTable: 'actors', enforceExists: true, keyColumns: ['_id'], actorScoped: false },",
      )
    }

    for (const [columnName, column] of Object.entries(def.columns)) {
      if (!column.referencedTable) {
        continue
      }

      const referencedTable = definitionsByName.get(column.referencedTable)

      if (!referencedTable) {
        throw new Error(
          `Missing table definition for "${column.referencedTable}" while emitting "${def.tableName}.${columnName}".`,
        )
      }

      const actorScoped =
        tableHasActorId(def.options) && tableHasActorId(referencedTable.options)
      const keyColumns = actorScoped ? ['_actor', '_id'] : ['_id']

      lines.push(
        `    ${columnName}: { referencedTable: '${column.referencedTable}', enforceExists: ${column.enforceExists}, keyColumns: ${renderStringArrayLiteral(keyColumns)}, actorScoped: ${actorScoped} },`,
      )
    }

    lines.push('  },')
  }
  lines.push('}')
  lines.push('')

  lines.push('export type IndexesByTable = {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: Record<string, SqliteIndexDefinition<readonly string[]>>`,
    )
  }
  lines.push('}')
  lines.push('')
  lines.push('export const INDEXES = {')
  for (const def of definitions) {
    lines.push(`  ${def.tableName}: {`)
    for (const index of getGeneratedIndexes(def)) {
      lines.push(
        `    ${index.name}: { fields: ${renderStringTuple(index.fields)}, unique: ${index.unique} },`,
      )
    }
    lines.push('  },')
  }
  lines.push('} as const satisfies IndexesByTable')
  lines.push('')

  lines.push(
    'export type SchemaValidatorDescriptorsByTable = Record<TableName, Record<string, ColumnValidatorDescriptor>>',
  )
  lines.push('')
  lines.push(
    'export const SCHEMA_VALIDATOR_DESCRIPTORS: SchemaValidatorDescriptorsByTable = {',
  )
  for (const def of definitions) {
    lines.push(`  ${JSON.stringify(def.tableName)}: {`)
    lines.push(
      `    "_id": ${renderValidatorDescriptorLiteral(systemIdValidatorDescriptor(def.tableName))},`,
    )
    for (const field of getImplicitSystemFields(def)) {
      lines.push(
        `    ${JSON.stringify(field.name)}: ${renderValidatorDescriptorLiteral(systemFieldValidatorDescriptor(field.name))},`,
      )
    }
    for (const [columnName, column] of Object.entries(def.columns)) {
      lines.push(
        `    ${JSON.stringify(columnName)}: ${renderValidatorDescriptorLiteral(column.validator)},`,
      )
    }
    lines.push('  },')
  }
  lines.push('}')
  lines.push('')

  lines.push('export type SchemaValidatorsByTable = Record<TableName, Record<string, string>>')
  lines.push('')
  lines.push('export const SCHEMA_VALIDATORS: SchemaValidatorsByTable = {')
  for (const def of definitions) {
    lines.push(`  ${JSON.stringify(def.tableName)}: {`)
    lines.push(`    "_id": "v.id()",`)
    for (const field of getImplicitSystemFields(def)) {
      lines.push(
        `    ${JSON.stringify(field.name)}: ${JSON.stringify(systemFieldValidator(field.name))},`,
      )
    }
    for (const [columnName, column] of Object.entries(def.columns)) {
      lines.push(
        `    ${JSON.stringify(columnName)}: ${JSON.stringify(renderValidatorSource(column.validator))},`,
      )
    }
    lines.push('  },')
  }
  lines.push('}')
  lines.push('')

  lines.push('export type SchemaSourcesByTable = Record<TableName, string>')
  lines.push('')
  lines.push('export const SCHEMA_SOURCES: SchemaSourcesByTable = {')
  for (const def of definitions) {
    lines.push(
      `  ${JSON.stringify(def.tableName)}: ${JSON.stringify(renderSchemaSource(def))},`,
    )
  }
  lines.push('}')
  lines.push('')

  lines.push('export interface SchemaCollections {')
  for (const def of definitions) {
    lines.push(
      `  ${def.tableName}: SqliteCollection<${rowTypeName(def.tableName)}, ${keyTypeName(def.tableName)}, typeof INDEXES.${def.tableName}>`,
    )
  }
  lines.push('}')
  lines.push('')

  lines.push(
    'export async function createCollections(db: AsyncSqliteDatabase): Promise<SchemaCollections> {',
  )
  lines.push('  return {')
  for (const def of definitions) {
    lines.push(
      `    ${def.tableName}: await createSqliteCollection<${rowTypeName(def.tableName)}, ${keyTypeName(def.tableName)}, typeof INDEXES.${def.tableName}>({`,
    )
    lines.push(`      id: 'sqlite-${def.tableName}',`)
    lines.push(`      tableName: '${def.tableName}',`)
    lines.push(`      keyColumns: KEY_COLUMNS.${def.tableName},`)
    lines.push(`      getKey: (row) => ${renderRowKey(def, 'row')},`)
    lines.push(`      serializeKey: (key) => ${renderSerializedKey(def, 'key')},`)
    lines.push(`      deserializeKey: (key) => ${renderDeserializedKey(def, 'key')},`)
    lines.push('      database: db,')
    lines.push(`      indexes: INDEXES.${def.tableName},`)
    lines.push(`      referenceColumns: REFERENCE_COLUMNS.${def.tableName},`)
    lines.push('    }),')
  }
  lines.push('  }')
  lines.push('}')
  lines.push('')

  lines.push('export function createBatchTransaction(')
  lines.push('  collections: SchemaCollections,')
  lines.push("  config?: Omit<TransactionConfig<AnyRow>, 'mutationFn'>,")
  lines.push(') {')
  lines.push('  return createTransaction<AnyRow>({')
  lines.push('    ...config,')
  lines.push('    mutationFn: async ({ transaction }) => {')
  for (const def of definitions) {
    lines.push(
      `      await collections.${def.tableName}.utils.persistMutations(transaction)`,
    )
  }
  lines.push('    },')
  lines.push('  })')
  lines.push('}')
  lines.push('')

  for (const def of definitions) {
    const rowType = rowTypeName(def.tableName)
    const singular = singularize(def.tableName)
    const plural = def.tableName
    const keyType = keyTypeName(def.tableName)
    const insertInputType = renderInsertInputType(def, rowType)
    const insertSystemFields = getInsertSystemFieldEntries(def, 'row')
    const updateChangesType = renderUpdateChangesType(def, rowType)

    lines.push(
      `export function insert${pascal(singular)}(collections: SchemaCollections, row: ${insertInputType}) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push(
      `    const completeRow = { ...row, ${insertSystemFields.join(', ')} } as ${rowType}`,
    )
    lines.push(`    collections.${def.tableName}.insert(completeRow)`)
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    if (tableUsesActorPrimaryKey(def.options)) {
      lines.push(
        `export function update${pascal(singular)}(collections: SchemaCollections, key: ${keyType}, changes: ${updateChangesType}) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push(
        `    collections.${def.tableName}.update(key, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'changes')}) })`,
      )
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')

      lines.push(
        `export function delete${pascal(singular)}(collections: SchemaCollections, key: ${keyType}) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push(`    collections.${def.tableName}.delete(key)`)
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')
    } else {
      lines.push(
        `export function update${pascal(singular)}(collections: SchemaCollections, _id: ${keyType}, changes: ${updateChangesType}) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push(
        `    collections.${def.tableName}.update(_id, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'changes')}) })`,
      )
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')

      lines.push(
        `export function delete${pascal(singular)}(collections: SchemaCollections, _id: ${keyType}) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push(`    collections.${def.tableName}.delete(_id)`)
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')
    }

    lines.push(
      `export function insert${pascal(plural)}(collections: SchemaCollections, rows: Array<${insertInputType}>) {`,
    )
    lines.push('  const tx = createBatchTransaction(collections)')
    lines.push('  tx.mutate(() => {')
    lines.push('    for (const row of rows) {')
    lines.push(
      `      const completeRow = { ...row, ${insertSystemFields.join(', ')} } as ${rowType}`,
    )
    lines.push(`      collections.${def.tableName}.insert(completeRow)`)
    lines.push('    }')
    lines.push('  })')
    lines.push('  return tx.isPersisted.promise')
    lines.push('}')
    lines.push('')

    if (tableUsesActorPrimaryKey(def.options)) {
      lines.push(
        `export function update${pascal(plural)}(collections: SchemaCollections, updates: Array<{ key: ${keyType}; changes: ${updateChangesType} }>) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push('    for (const update of updates) {')
      lines.push(
        `      collections.${def.tableName}.update(update.key, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'update.changes')}) })`,
      )
      lines.push('    }')
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')

      lines.push(
        `export function delete${pascal(plural)}(collections: SchemaCollections, keys: ${keyType}[]) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push('    for (const key of keys) {')
      lines.push(`      collections.${def.tableName}.delete(key)`)
      lines.push('    }')
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')
    } else {
      lines.push(
        `export function update${pascal(plural)}(collections: SchemaCollections, updates: Array<{ _id: ${keyType}; changes: ${updateChangesType} }>) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push('    for (const update of updates) {')
      lines.push(
        `      collections.${def.tableName}.update(update._id, (draft) => { Object.assign(draft, ${renderUpdateAssignment(def, 'update.changes')}) })`,
      )
      lines.push('    }')
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')

      lines.push(
        `export function delete${pascal(plural)}(collections: SchemaCollections, ids: ${keyType}[]) {`,
      )
      lines.push('  const tx = createBatchTransaction(collections)')
      lines.push('  tx.mutate(() => {')
      lines.push('    for (const _id of ids) {')
      lines.push(`      collections.${def.tableName}.delete(_id)`)
      lines.push('    }')
      lines.push('  })')
      lines.push('  return tx.isPersisted.promise')
      lines.push('}')
      lines.push('')
    }
  }

  return lines.join('\n')
}

function rowTypeName(tableName: string): string {
  return pascal(singularize(tableName)) + 'Row'
}

function hashDefinitions(definitions: TableDefinition[]): string {
  const stablePayload = JSON.stringify(
    definitions.map((definition) => ({
      tableName: definition.tableName,
      options: definition.options,
      indexes: definition.indexes,
      columns: Object.fromEntries(
        Object.entries(definition.columns).map(([columnName, column]) => [
          columnName,
          {
            sqliteType: column.sqliteType,
            tsType: column.tsType,
            isNullable: column.isNullable,
            defaultValue: column.defaultValue,
            referencedTable: column.referencedTable,
            enforceExists: column.enforceExists,
            jsonKind: column.jsonKind,
            validator: column.validator,
          },
        ]),
      ),
    })),
  )

  return createHash('sha256').update(stablePayload).digest('hex')
}

function keyTypeName(tableName: string): string {
  return pascal(singularize(tableName)) + 'Key'
}

function pascal(str: string): string {
  return str
    .split(/[_-]/)
    .map((segment) => segment.charAt(0).toUpperCase() + segment.slice(1))
    .join('')
}

function singularize(name: string): string {
  if (name.endsWith('ies')) {
    return name.slice(0, -3) + 'y'
  }
  if (name.endsWith('ses') || name.endsWith('xes') || name.endsWith('zes')) {
    return name.slice(0, -2)
  }
  if (name.endsWith('s') && !name.endsWith('ss')) {
    return name.slice(0, -1)
  }
  return name
}

function sqlLiteral(value: unknown): string {
  if (typeof value === 'string') {
    return `'${value.replace(/'/g, "''")}'`
  }
  if (typeof value === 'bigint') {
    return value.toString()
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }
  if (Array.isArray(value) || isPlainObject(value)) {
    return `'${JSON.stringify(value).replace(/'/g, "''")}'`
  }
  return 'NULL'
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function renderTsType(column: ColumnDescriptor): string {
  if (column.referencedTable !== undefined) {
    return column.isNullable
      ? `Id<'${column.referencedTable}'> | null`
      : `Id<'${column.referencedTable}'>`
  }

  return column.tsType
}

function renderValidatorSource(validator: ColumnValidatorDescriptor): string {
  switch (validator.kind) {
    case 'string':
      return 'v.string()'
    case 'number':
      return 'v.number()'
    case 'float':
      return 'v.float()'
    case 'boolean':
      return 'v.boolean()'
    case 'id':
      return validator.enforceExists
        ? `v.id('${validator.referencedTable}', { enforceExists: true })`
        : `v.id('${validator.referencedTable}')`
    case 'array':
      return `v.array(${renderValidatorSource(validator.element)})`
    case 'object':
      return `v.object({ ${Object.entries(validator.fields)
        .map(
          ([fieldName, fieldValidator]) =>
            `${fieldName}: ${renderValidatorSource(fieldValidator)}`,
        )
        .join(', ')} })`
    case 'record':
      return `v.record(${renderValidatorSource(validator.keys)}, ${renderValidatorSource(validator.values)})`
    case 'nullable':
      return `v.nullable(${renderValidatorSource(validator.inner)})`
    case 'default':
      return `v.default(${renderValidatorSource(validator.inner)}, ${renderJsValueLiteral(validator.value)})`
  }
}

function renderValidatorDescriptorLiteral(
  validator: ColumnValidatorDescriptor,
): string {
  return renderJsValueLiteral(validator)
}

function renderSchemaSource(def: TableDefinition): string {
  const schemaFields = Object.entries(def.columns).map(
    ([columnName, column]) =>
      `  ${columnName}: ${renderValidatorSource(column.validator)},`,
  )

  let source = `import { defineTable, v } from '@sink/lib'\n\nexport default defineTable('${def.tableName}', {\n${schemaFields.join('\n')}\n})`

  if (!tableUsesAutogeneratedId(def.options)) {
    source += '\n  .withId({ autogenerated: false })'
  }

  if (def.options.withActorId) {
    if (def.options.actorIdPrimaryKey) {
      source += '\n  .withActorId(true, { pk: true })'
    } else {
      source += '\n  .withActorId(true)'
    }
  }

  if (def.options.withCreatedAt) {
    source += '\n  .withCreatedAt(true)'
  }

  if (def.options.withUpdatedAt) {
    source += '\n  .withUpdatedAt(true)'
  }

  if (def.options.withArchivedAt) {
    source += '\n  .withArchivedAt(true)'
  }

  for (const index of def.indexes) {
    if (index.staged) {
      source += `\n  .index('${index.name}', { fields: ${renderStringArrayLiteral(index.fields)}, staged: true${index.unique ? ', unique: true' : ''} })`
      continue
    }

    const methodName = index.unique ? 'uniqueIndex' : 'index'
    source += `\n  .${methodName}('${index.name}', ${renderStringArrayLiteral(index.fields)})`
  }

  return source
}

function renderJsValueLiteral(value: unknown): string {
  if (typeof value === 'string') {
    return JSON.stringify(value)
  }

  if (typeof value === 'bigint') {
    return `${value}n`
  }

  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value)
  }

  if (value === null) {
    return 'null'
  }

  if (Array.isArray(value)) {
    return `[${value.map((item) => renderJsValueLiteral(item)).join(', ')}]`
  }

  if (isPlainObject(value)) {
    return `{ ${Object.entries(value)
      .map(
        ([key, nestedValue]) =>
          `${JSON.stringify(key)}: ${renderJsValueLiteral(nestedValue)}`,
      )
      .join(', ')} }`
  }

  return 'undefined'
}

function renderStringArrayLiteral(values: readonly string[]): string {
  return `[${values.map((value) => JSON.stringify(value)).join(', ')}]`
}

function systemIdValidatorDescriptor(tableName: string): ColumnValidatorDescriptor {
  return {
    kind: 'id',
    referencedTable: tableName,
    enforceExists: false,
  }
}

function systemFieldValidatorDescriptor(fieldName: string): ColumnValidatorDescriptor {
  switch (fieldName) {
    case '_actor':
      return {
        kind: 'id',
        referencedTable: 'actors',
        enforceExists: true,
      }
    case '_createdAt':
    case '_updatedAt':
      return { kind: 'number' }
    case '_archivedAt':
      return {
        kind: 'nullable',
        inner: { kind: 'number' },
      }
    default:
      return { kind: 'string' }
  }
}

function systemFieldValidator(fieldName: string): string {
  switch (fieldName) {
    case '_actor':
      return "v.id('actors', { enforceExists: true })"
    case '_createdAt':
      return 'v.number()'
    case '_updatedAt':
      return 'v.number()'
    case '_archivedAt':
      return 'v.nullable(v.number())'
    default:
      return 'v.string()'
  }
}

function systemIdTsType(tableName: string): string {
  return `Id<'${tableName}'>`
}

function getImplicitSystemFields(def: TableDefinition): Array<{
  name: string
  tsType: string
  sqliteType: string
}> {
  const fields: Array<{ name: string; tsType: string; sqliteType: string }> = []

  if (tableHasActorId(def.options)) {
    fields.push({
      name: '_actor',
      tsType: "Id<'actors'>",
      sqliteType: 'TEXT NOT NULL',
    })
  }

  if (def.options.withCreatedAt) {
    fields.push({
      name: '_createdAt',
      tsType: 'bigint',
      sqliteType: 'INTEGER NOT NULL',
    })
  }

  if (def.options.withUpdatedAt) {
    fields.push({
      name: '_updatedAt',
      tsType: 'bigint',
      sqliteType: 'INTEGER NOT NULL',
    })
  }

  if (def.options.withArchivedAt) {
    fields.push({
      name: '_archivedAt',
      tsType: 'bigint | null',
      sqliteType: 'INTEGER',
    })
  }

  return fields
}

function getOptionalInsertSystemFieldNames(def: TableDefinition): string[] {
  const fieldNames: string[] = []

  if (def.options.withCreatedAt) {
    fieldNames.push('_createdAt')
  }

  if (def.options.withUpdatedAt) {
    fieldNames.push('_updatedAt')
  }

  if (def.options.withArchivedAt) {
    fieldNames.push('_archivedAt')
  }

  return fieldNames
}

function getInsertSystemFieldEntries(
  def: TableDefinition,
  sourceName: string,
): string[] {
  const fields = [
    tableUsesAutogeneratedId(def.options)
      ? tableUsesActorPrimaryKey(def.options)
        ? `_id: ${sourceName}._id ?? createId<'${def.tableName}'>()`
        : `_id: createId<'${def.tableName}'>()`
      : `_id: ${sourceName}._id`,
  ]

  if (def.options.withCreatedAt) {
    fields.push(`_createdAt: ${sourceName}._createdAt ?? currentTimestamp()`)
  }

  if (def.options.withUpdatedAt) {
    fields.push(`_updatedAt: ${sourceName}._updatedAt ?? currentTimestamp()`)
  }

  if (def.options.withArchivedAt) {
    fields.push(`_archivedAt: ${sourceName}._archivedAt ?? null`)
  }

  return fields
}

function renderInsertInputType(def: TableDefinition, rowType: string): string {
  const omittedFields = [
    ...getOptionalInsertSystemFieldNames(def),
    ...(tableUsesAutogeneratedId(def.options) ? ['_id'] : []),
  ].map((fieldName) => `'${fieldName}'`)
  const optionalFields = [
    ...(tableUsesAutogeneratedId(def.options) && tableUsesActorPrimaryKey(def.options)
      ? ['_id']
      : []),
    ...getOptionalInsertSystemFieldNames(def),
  ].map((fieldName) => `'${fieldName}'`)

  let typeSource = omittedFields.length > 0
    ? `Omit<${rowType}, ${omittedFields.join(' | ')}>`
    : rowType

  if (optionalFields.length > 0) {
    typeSource += ` & Partial<Pick<${rowType}, ${optionalFields.join(' | ')}>>`
  }

  return typeSource
}

function renderUpdateChangesType(def: TableDefinition, rowType: string): string {
  const primaryKeyFields = getPrimaryKeyColumns(def.options).map(
    (fieldName) => `'${fieldName}'`,
  )

  return `Partial<Omit<${rowType}, ${primaryKeyFields.join(' | ')}>>`
}

function renderUpdateAssignment(def: TableDefinition, sourceName: string): string {
  if (!def.options.withUpdatedAt) {
    return sourceName
  }

  return `{ ...${sourceName}, _updatedAt: ${sourceName}._updatedAt ?? currentTimestamp() }`
}

function renderRowKey(def: TableDefinition, sourceName: string): string {
  if (tableUsesActorPrimaryKey(def.options)) {
    return `({ _actor: ${sourceName}._actor, _id: ${sourceName}._id })`
  }

  return `${sourceName}._id`
}

function renderSerializedKey(def: TableDefinition, sourceName: string): string {
  if (tableUsesActorPrimaryKey(def.options)) {
    return `JSON.stringify([['_actor', ${sourceName}._actor], ['_id', ${sourceName}._id]])`
  }

  return sourceName
}

function renderDeserializedKey(def: TableDefinition, sourceName: string): string {
  if (tableUsesActorPrimaryKey(def.options)) {
    return `(() => {
        const entries = JSON.parse(String(${sourceName})) as Array<[string, string]>
        return { _actor: entries[0]?.[1] as Id<'actors'>, _id: entries[1]?.[1] as ${systemIdTsType(def.tableName)} }
      })()`
  }

  return `${sourceName} as ${systemIdTsType(def.tableName)}`
}

function getGeneratedIndexes(def: TableDefinition): Array<{
  name: string
  fields: readonly string[]
  unique: boolean
  createSql: string | null
}> {
  const primaryKeyColumns = getPrimaryKeyColumns(def.options)
  const indexes: Array<{
    name: string
    fields: readonly string[]
    unique: boolean
    createSql: string | null
  }> = [
    {
      name: 'by_id',
      fields: primaryKeyColumns,
      unique: true,
      createSql: null,
    },
  ]

  if (def.options.withCreatedAt) {
    const fields = appendUniqueFields(['_createdAt'], primaryKeyColumns)
    indexes.push({
      name: 'by_creation_time',
      fields,
      unique: false,
      createSql: createIndexSql(def.tableName, 'by_creation_time', fields, false),
    })
  }

  for (const index of def.indexes) {
    const trailingFields = def.options.withCreatedAt
      ? appendUniqueFields(['_createdAt'], primaryKeyColumns)
      : primaryKeyColumns
    const fields = index.unique
      ? index.fields
      : appendUniqueFields(index.fields, trailingFields)

    indexes.push({
      name: index.name,
      fields,
      unique: index.unique,
      createSql: createIndexSql(def.tableName, index.name, fields, index.unique),
    })
  }

  return indexes
}

function appendUniqueFields(
  leadingFields: readonly string[],
  trailingFields: readonly string[],
): readonly string[] {
  const fields: string[] = [...leadingFields]

  for (const field of trailingFields) {
    if (!fields.includes(field)) {
      fields.push(field)
    }
  }

  return fields
}

function createIndexSql(
  tableName: string,
  indexName: string,
  fields: readonly string[],
  unique: boolean,
): string {
  const expressions = fields.map(fieldPathToSqlExpression)

  return `CREATE ${unique ? 'UNIQUE ' : ''}INDEX IF NOT EXISTS "${escapeSqlIdentifier(`idx_${tableName}_${indexName}`)}" ON "${escapeSqlIdentifier(tableName)}" (${expressions.join(', ')});`
}

function fieldPathToSqlExpression(fieldPath: string): string {
  if (!fieldPath.includes('.')) {
    return `"${escapeSqlIdentifier(fieldPath)}"`
  }

  const [root, ...segments] = fieldPath.split('.')
  const jsonPath = `$.${segments.join('.')}`

  if (!root) {
    throw new Error(`Invalid field path "${fieldPath}".`)
  }

  return `json_extract("${escapeSqlIdentifier(root)}", '${jsonPath.replace(/'/g, "''")}')`
}

function escapeSqlIdentifier(identifier: string): string {
  return identifier.replace(/"/g, '""')
}

function renderStringTuple(fields: readonly string[]): string {
  return `[${fields.map((field) => `'${field}'`).join(', ')}] as const`
}

function renderStringTupleType(fields: readonly string[]): string {
  return `readonly [${fields.map((field) => `'${field}'`).join(', ')}]`
}

function renderStringArray(values: readonly string[]): string {
  return `[${values.map((value) => `\`${value.replace(/`/g, '\\`')}\``).join(', ')}]`
}
