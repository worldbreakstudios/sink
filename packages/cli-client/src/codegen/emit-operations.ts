import path from 'node:path'
import {
  getPrimaryKeyColumns,
  type TableDefinition,
} from '@sink/lib'

interface EmitOperationsOptions {
  definitions: TableDefinition[]
  schemaOutputPath: string
  operationsOutputPath: string
  policyFiles: string[]
  queryFiles: string[]
  mutationFiles: string[]
}

export function emitOperations(options: EmitOperationsOptions): string {
  const lines: string[] = []
  const schemaImportPath = toImportPath(
    options.operationsOutputPath,
    options.schemaOutputPath,
  )
  const policyImports = options.policyFiles.map((file, index) => ({
    file,
    localName: `__policyModule${index}`,
  }))
  const queryImports = options.queryFiles.map((file, index) => ({
    file,
    localName: `__queryModule${index}`,
  }))
  const mutationImports = options.mutationFiles.map((file, index) => ({
    file,
    localName: `__mutationModule${index}`,
  }))

  lines.push('// Auto-generated by `sink generate` — do not edit manually.')
  lines.push('// @ts-nocheck')
  lines.push('')
  lines.push(
    "import type { AsyncSqliteDatabase, CreateSyncBatchTransaction, SyncClient, SyncMutationDefinition, SyncQueryDefinition, SyncSchemaMetadata, SyncSocketLike } from '@sink/lib'",
  )
  lines.push(
    "import { assertAuthorized, collectDefinedMutations, collectDefinedPolicies, collectDefinedQueries, createPrimaryLockTarget, createSyncClient, createUniqueLockTarget, defineMutation, defineQuery, getRowKey, invalidationTouchesTable, mergeSyncOperationRegistry, readLocalRowsForTable, reconcileScopedRows, resolveReadScope, rowMatchesWhere, runMutationPolicyExistingPhases, runMutationPolicyInputPhases, runPolicyAfterCommit, sortRows, syncValuesEqual, validateReferenceColumns } from '@sink/lib'",
  )
  lines.push(
    `import { ID_AUTOGENERATED, KEY_COLUMNS, REFERENCE_COLUMNS, SCHEMA_HASH, SCHEMA_VALIDATOR_DESCRIPTORS } from ${JSON.stringify(schemaImportPath)}`,
  )
  lines.push(
    `import type { SchemaCollections${renderSchemaTypeImports(options.definitions)} } from ${JSON.stringify(schemaImportPath)}`,
  )
  for (const policyImport of policyImports) {
    lines.push(
      `import * as ${policyImport.localName} from ${JSON.stringify(
        toImportPath(options.operationsOutputPath, policyImport.file),
      )}`,
    )
  }
  for (const queryImport of queryImports) {
    lines.push(
      `import * as ${queryImport.localName} from ${JSON.stringify(
        toImportPath(options.operationsOutputPath, queryImport.file),
      )}`,
    )
  }
  for (const mutationImport of mutationImports) {
    lines.push(
      `import * as ${mutationImport.localName} from ${JSON.stringify(
        toImportPath(options.operationsOutputPath, mutationImport.file),
      )}`,
    )
  }
  lines.push('')
  lines.push(
    'export const SYNC_METADATA = {',
  )
  lines.push("  schemaHash: SCHEMA_HASH,")
  lines.push('  tables: {')
  for (const def of options.definitions) {
    const generatedIndexes = getGeneratedIndexes(def)
    const defaultListIndexName = getDefaultListIndexName(def)
    lines.push(`    ${def.tableName}: {`)
    lines.push(`      keyColumns: KEY_COLUMNS.${def.tableName},`)
    lines.push(`      referenceColumns: REFERENCE_COLUMNS.${def.tableName},`)
    lines.push(`      validatorDescriptors: SCHEMA_VALIDATOR_DESCRIPTORS.${def.tableName},`)
    lines.push('      indexes: {')
    for (const index of generatedIndexes) {
      lines.push(`        ${index.name}: {`)
      lines.push(`          fields: ${renderStringTuple(index.fields)},`)
      lines.push(`          unique: ${index.unique},`)
      lines.push(`          filterFields: ${renderStringTuple(index.filterFields)},`)
      lines.push('        },')
    }
    lines.push('      },')
    lines.push(`      autogeneratedId: ID_AUTOGENERATED.${def.tableName},`)
    lines.push(`      hasCreatedAt: ${Boolean(def.options.withCreatedAt)},`)
    lines.push(`      hasUpdatedAt: ${Boolean(def.options.withUpdatedAt)},`)
    lines.push(`      hasArchivedAt: ${Boolean(def.options.withArchivedAt)},`)
    lines.push(`      defaultListIndexName: '${defaultListIndexName}',`)
    lines.push('    },')
  }
  lines.push('  },')
  lines.push('} as const satisfies SyncSchemaMetadata')
  lines.push('')

  for (const def of options.definitions) {
    const tableName = def.tableName
    const rowType = rowTypeName(tableName)
    const keyType = keyTypeName(tableName)
    const keyColumns = getPrimaryKeyColumns(def.options)
    const defaultListIndex = getGeneratedIndexes(def).find(
      (index) => index.name === getDefaultListIndexName(def),
    ) ?? getGeneratedIndexes(def)[0]
    const defaultListOrder = defaultListIndex?.fields ?? keyColumns

    const listArgsName = `${rowType}ListArgs`
    lines.push(`export interface ${listArgsName} {}`)
    lines.push(
      `export const ${camelCase(tableName)}ListQuery = defineQuery<${listArgsName}, ${rowType}[], SchemaCollections>({`,
    )
    lines.push("  kind: 'query',")
    lines.push(`  name: '${tableName}.list',`)
    lines.push(`  tables: ['${tableName}'],`)
    lines.push('  async readLocal(context) {')
    lines.push(`    const rows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
    lines.push(
      `    return sortRows(rows, ${renderOrderBy(defaultListOrder)} ) as ${rowType}[]`,
    )
    lines.push('  },')
    lines.push('  async runServer(context, args) {')
    lines.push(`    const policy = context.policies['${tableName}']`)
    lines.push(`    const policyContext = { auth: context.auth, args, tableName: '${tableName}', operationName: '${tableName}.list', action: 'list' as const }`)
    lines.push(`    assertAuthorized(await policy?.authorize?.(policyContext), '${tableName}.list')`)
    lines.push('    const where = await resolveReadScope(policy, policyContext)')
    lines.push(
      `    return await context.adapter.listRows('${tableName}', { where, orderBy: ${renderOrderBy(defaultListOrder)} }) as ${rowType}[]`,
    )
    lines.push('  },')
    lines.push('  async mergeServer(context, _args, result) {')
    lines.push(
      `    await reconcileScopedRows(context, SYNC_METADATA, '${tableName}', result, () => true)`,
    )
    lines.push('  },')
    lines.push('  matchesInvalidation(_args, targets) {')
    lines.push(`    return invalidationTouchesTable(targets, '${tableName}')`)
    lines.push('  },')
    lines.push('})')
    lines.push('')

    const getArgsName = `${rowType}GetArgs`
    lines.push(`export interface ${getArgsName} {`)
    lines.push(`  key: ${keyType}`)
    lines.push('}')
    lines.push(
      `export const ${camelCase(tableName)}GetQuery = defineQuery<${getArgsName}, ${rowType} | null, SchemaCollections>({`,
    )
    lines.push("  kind: 'query',")
    lines.push(`  name: '${tableName}.get',`)
    lines.push(`  tables: ['${tableName}'],`)
    lines.push('  async readLocal(context, args) {')
    lines.push(`    const rows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
    lines.push(
      `    const serializedKey = JSON.stringify(args.key)`,
    )
    lines.push(
      `    return (rows.find((row) => JSON.stringify(getRowKey(SYNC_METADATA.tables.${tableName}, row)) === serializedKey) ?? null)`,
    )
    lines.push('  },')
    lines.push('  async runServer(context, args) {')
    lines.push(`    const policy = context.policies['${tableName}']`)
    lines.push(`    const policyContext = { auth: context.auth, args, tableName: '${tableName}', operationName: '${tableName}.get', action: 'get' as const }`)
    lines.push(`    assertAuthorized(await policy?.authorize?.(policyContext), '${tableName}.get')`)
    lines.push('    const readScope = await resolveReadScope(policy, policyContext)')
    lines.push(
      `    const row = await context.adapter.getRowByKey('${tableName}', args.key, SYNC_METADATA.tables.${tableName}.keyColumns)`,
    )
    lines.push('    if (!row) {')
    lines.push('      return null')
    lines.push('    }')
    lines.push('    if (readScope.length > 0 && !rowMatchesWhere(row, readScope)) {')
    lines.push('      return null')
    lines.push('    }')
    lines.push(`    return row as ${rowType}`)
    lines.push('  },')
    lines.push('  async mergeServer(context, args, result) {')
    lines.push(
      `    const serializedKey = JSON.stringify(args.key)`,
    )
    lines.push(
      `    await reconcileScopedRows(context, SYNC_METADATA, '${tableName}', result ? [result] : [], (row) => JSON.stringify(getRowKey(SYNC_METADATA.tables.${tableName}, row)) === serializedKey)`,
    )
    lines.push('  },')
    lines.push('  matchesInvalidation(_args, targets) {')
    lines.push(`    return invalidationTouchesTable(targets, '${tableName}')`)
    lines.push('  },')
    lines.push('})')
    lines.push('')

    for (const index of getGeneratedIndexes(def)) {
      if (index.name === 'by_id' || index.name === 'by_creation_time') {
        continue
      }

      const argsName = `${rowType}${pascalCase(index.name)}Args`
      const valuesType = renderValuesType(index.filterFields, def)
      const orderFields = renderOrderBy(index.fields)

      if (index.unique) {
        lines.push(`export interface ${argsName} {`)
        lines.push(`  values: ${valuesType}`)
        lines.push('}')
        lines.push(
          `export const ${camelCase(tableName)}GetBy${pascalCase(index.name)}Query = defineQuery<${argsName}, ${rowType} | null, SchemaCollections>({`,
        )
        lines.push("  kind: 'query',")
        lines.push(`  name: '${tableName}.getBy.${index.name}',`)
        lines.push(`  tables: ['${tableName}'],`)
        lines.push('  async readLocal(context, args) {')
        lines.push(`    const rows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
        lines.push(
          `    return (rows.find((row) => rowMatchesWhere(row, ${renderWhereFromValues('args.values')})) ?? null)`,
        )
        lines.push('  },')
        lines.push('  async runServer(context, args) {')
        lines.push(`    const policy = context.policies['${tableName}']`)
        lines.push(`    const policyContext = { auth: context.auth, args, tableName: '${tableName}', operationName: '${tableName}.getBy.${index.name}', action: 'getBy' as const, indexName: '${index.name}' }`)
        lines.push(`    assertAuthorized(await policy?.authorize?.(policyContext), '${tableName}.getBy.${index.name}')`)
        lines.push('    const readScope = await resolveReadScope(policy, policyContext)')
        lines.push(
          `    const rows = await context.adapter.listRows('${tableName}', { where: [...readScope, ...${renderWhereFromValues('args.values')}], orderBy: ${orderFields}, limit: 1 })`,
        )
        lines.push(`    return (rows[0] ?? null) as ${rowType} | null`)
        lines.push('  },')
        lines.push('  async mergeServer(context, args, result) {')
        lines.push(
          `    await reconcileScopedRows(context, SYNC_METADATA, '${tableName}', result ? [result] : [], (row) => rowMatchesWhere(row, ${renderWhereFromValues('args.values')}))`,
        )
        lines.push('  },')
        lines.push('  matchesInvalidation(_args, targets) {')
        lines.push(`    return invalidationTouchesTable(targets, '${tableName}')`)
        lines.push('  },')
        lines.push('})')
        lines.push('')
      } else {
        lines.push(`export interface ${argsName} {`)
        lines.push(`  values: ${valuesType}`)
        lines.push('}')
        lines.push(
          `export const ${camelCase(tableName)}ListBy${pascalCase(index.name)}Query = defineQuery<${argsName}, ${rowType}[], SchemaCollections>({`,
        )
        lines.push("  kind: 'query',")
        lines.push(`  name: '${tableName}.listBy.${index.name}',`)
        lines.push(`  tables: ['${tableName}'],`)
        lines.push('  async readLocal(context, args) {')
        lines.push(`    const rows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
        lines.push(
          `    return sortRows(rows.filter((row) => rowMatchesWhere(row, ${renderWhereFromValues('args.values')})), ${orderFields})`,
        )
        lines.push('  },')
        lines.push('  async runServer(context, args) {')
        lines.push(`    const policy = context.policies['${tableName}']`)
        lines.push(`    const policyContext = { auth: context.auth, args, tableName: '${tableName}', operationName: '${tableName}.listBy.${index.name}', action: 'listBy' as const, indexName: '${index.name}' }`)
        lines.push(`    assertAuthorized(await policy?.authorize?.(policyContext), '${tableName}.listBy.${index.name}')`)
        lines.push('    const readScope = await resolveReadScope(policy, policyContext)')
        lines.push(
          `    return await context.adapter.listRows('${tableName}', { where: [...readScope, ...${renderWhereFromValues('args.values')}], orderBy: ${orderFields} }) as ${rowType}[]`,
        )
        lines.push('  },')
        lines.push('  async mergeServer(context, args, result) {')
        lines.push(
          `    await reconcileScopedRows(context, SYNC_METADATA, '${tableName}', result, (row) => rowMatchesWhere(row, ${renderWhereFromValues('args.values')}))`,
        )
        lines.push('  },')
        lines.push('  matchesInvalidation(_args, targets) {')
        lines.push(`    return invalidationTouchesTable(targets, '${tableName}')`)
        lines.push('  },')
        lines.push('})')
        lines.push('')
      }
    }

    const updateChangesType = renderUpdateChangesType(def, rowType)
    lines.push(`export interface ${rowType}InsertArgs {`)
    lines.push(`  row: ${rowType}`)
    lines.push('}')
    lines.push(
      `export const ${camelCase(tableName)}InsertMutation = defineMutation<${rowType}InsertArgs, ${rowType}, ${rowType}, SchemaCollections>({`,
    )
    lines.push("  kind: 'mutation',")
    lines.push(`  name: '${tableName}.insert',`)
    lines.push('  lockTargets(args) {')
    lines.push(
      `    return [createPrimaryLockTarget(SYNC_METADATA.tables.${tableName}, '${tableName}', getRowKey(SYNC_METADATA.tables.${tableName}, args.row))]`,
    )
    lines.push('  },')
    lines.push('  async applyLocal(context, args) {')
    lines.push(
      `    context.transaction.mutate(() => { context.collections.${tableName}.insert(args.row as any) })`,
    )
    lines.push('    return args.row')
    lines.push('  },')
    lines.push('  async runServer(context, args) {')
    lines.push(`    const policy = context.policies['${tableName}']`)
    lines.push(`    const policyContext = { auth: context.auth, args, existingRow: null, force: context.force, tableName: '${tableName}', operationName: '${tableName}.insert', action: 'insert' as const }`)
    lines.push(`    const input = await runMutationPolicyInputPhases(policy, policyContext, args.row as unknown as Record<string, unknown>)`)
    lines.push(`    await validateReferenceColumns(context.adapter, context.metadata, '${tableName}', input)`)
    lines.push(`    const result = await context.adapter.insertRow('${tableName}', input)`)
    lines.push(`    await runPolicyAfterCommit(policy, policyContext, result)`)
    lines.push(`    return result as ${rowType}`)
    lines.push('  },')
    lines.push('  resultsEqual(localResult, serverResult) {')
    lines.push('    return syncValuesEqual(localResult, serverResult)')
    lines.push('  },')
    lines.push('  invalidate(_args, result) {')
    lines.push(`    return [{ tableName: '${tableName}', keys: [getRowKey(SYNC_METADATA.tables.${tableName}, result)] }]`)
    lines.push('  },')
    lines.push('})')
    lines.push('')

    lines.push(`export interface ${rowType}UpdateArgs {`)
    lines.push(`  key: ${keyType}`)
    lines.push(`  changes: ${updateChangesType}`)
    lines.push('}')
    lines.push(
      `export const ${camelCase(tableName)}UpdateMutation = defineMutation<${rowType}UpdateArgs, ${rowType}, ${rowType}, SchemaCollections>({`,
    )
    lines.push("  kind: 'mutation',")
    lines.push(`  name: '${tableName}.update',`)
    lines.push('  lockTargets(args) {')
    lines.push(
      `    return [createPrimaryLockTarget(SYNC_METADATA.tables.${tableName}, '${tableName}', args.key)]`,
    )
    lines.push('  },')
    lines.push('  async applyLocal(context, args) {')
    lines.push(`    const currentRows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
    lines.push(`    const serializedKey = JSON.stringify(args.key)`)
    lines.push(
      `    const currentRow = currentRows.find((row) => JSON.stringify(getRowKey(SYNC_METADATA.tables.${tableName}, row)) === serializedKey)`,
    )
    lines.push('    if (!currentRow) { throw new Error(\'Row not found.\') }')
    lines.push(`    const nextRow = { ...currentRow, ...args.changes } as ${rowType}`)
    lines.push(
      `    context.transaction.mutate(() => { context.collections.${tableName}.update(args.key as any, (draft) => { Object.assign(draft, args.changes) }) })`,
    )
    lines.push('    return nextRow')
    lines.push('  },')
    lines.push('  async runServer(context, args) {')
    lines.push(`    const policy = context.policies['${tableName}']`)
    lines.push(`    const existingRow = await context.adapter.getRowByKey('${tableName}', args.key, SYNC_METADATA.tables.${tableName}.keyColumns)`)
    lines.push(`    if (!existingRow) { throw new Error('Row not found.') }`)
    lines.push(`    const policyContext = { auth: context.auth, args, existingRow, force: context.force, tableName: '${tableName}', operationName: '${tableName}.update', action: 'update' as const }`)
    lines.push(`    const changes = await runMutationPolicyInputPhases(policy, policyContext, args.changes as unknown as Record<string, unknown>)`)
    lines.push(`    await runMutationPolicyExistingPhases(policy, policyContext)`)
    lines.push(`    await validateReferenceColumns(context.adapter, context.metadata, '${tableName}', { ...existingRow, ...changes })`)
    lines.push(`    const result = await context.adapter.updateRow('${tableName}', args.key, changes, SYNC_METADATA.tables.${tableName}.keyColumns)`)
    lines.push(`    await runPolicyAfterCommit(policy, policyContext, result)`)
    lines.push(`    return result as ${rowType}`)
    lines.push('  },')
    lines.push('  resultsEqual(localResult, serverResult) {')
    lines.push('    return syncValuesEqual(localResult, serverResult)')
    lines.push('  },')
    lines.push('  invalidate(_args, result) {')
    lines.push(`    return [{ tableName: '${tableName}', keys: [getRowKey(SYNC_METADATA.tables.${tableName}, result)] }]`)
    lines.push('  },')
    lines.push('})')
    lines.push('')

    lines.push(`export interface ${rowType}DeleteArgs {`)
    lines.push(`  key: ${keyType}`)
    lines.push('}')
    lines.push(
      `export const ${camelCase(tableName)}DeleteMutation = defineMutation<${rowType}DeleteArgs, { key: ${keyType} }, { key: ${keyType} }, SchemaCollections>({`,
    )
    lines.push("  kind: 'mutation',")
    lines.push(`  name: '${tableName}.delete',`)
    lines.push('  lockTargets(args) {')
    lines.push(
      `    return [createPrimaryLockTarget(SYNC_METADATA.tables.${tableName}, '${tableName}', args.key)]`,
    )
    lines.push('  },')
    lines.push('  async applyLocal(context, args) {')
    lines.push(
      `    context.transaction.mutate(() => { context.collections.${tableName}.delete(args.key as any) })`,
    )
    lines.push('    return { key: args.key }')
    lines.push('  },')
    lines.push('  async runServer(context, args) {')
    lines.push(`    const policy = context.policies['${tableName}']`)
    lines.push(`    const existingRow = await context.adapter.getRowByKey('${tableName}', args.key, SYNC_METADATA.tables.${tableName}.keyColumns)`)
    lines.push(`    if (!existingRow) { throw new Error('Row not found.') }`)
    lines.push(`    const policyContext = { auth: context.auth, args, existingRow, force: context.force, tableName: '${tableName}', operationName: '${tableName}.delete', action: 'delete' as const }`)
    lines.push(`    assertAuthorized(await policy?.authorize?.(policyContext), '${tableName}.delete')`)
    lines.push(`    await runMutationPolicyExistingPhases(policy, policyContext)`)
    lines.push(`    await context.adapter.deleteRow('${tableName}', args.key, SYNC_METADATA.tables.${tableName}.keyColumns)`)
    lines.push(`    const result = { key: args.key }`)
    lines.push(`    await runPolicyAfterCommit(policy, policyContext, result)`)
    lines.push('    return result')
    lines.push('  },')
    lines.push('  resultsEqual(localResult, serverResult) {')
    lines.push('    return syncValuesEqual(localResult, serverResult)')
    lines.push('  },')
    lines.push('  invalidate(args) {')
    lines.push(`    return [{ tableName: '${tableName}', keys: [args.key] }]`)
    lines.push('  },')
    lines.push('})')
    lines.push('')

    for (const index of getGeneratedIndexes(def).filter((index) => index.unique && index.name !== 'by_id')) {
      const argsName = `${rowType}${pascalCase(index.name)}UpsertArgs`
      lines.push(`export interface ${argsName} {`)
      lines.push(`  values: ${renderValuesType(index.filterFields, def)}`)
      lines.push(`  create: ${rowType}`)
      lines.push(`  update: ${updateChangesType}`)
      lines.push('}')
      lines.push(
        `export interface ${rowType}${pascalCase(index.name)}UpsertResult {`,
      )
      lines.push(`  row: ${rowType}`)
      lines.push(`  mode: 'inserted' | 'updated'`)
      lines.push('}')
      lines.push(
        `export const ${camelCase(tableName)}UpsertBy${pascalCase(index.name)}Mutation = defineMutation<${argsName}, ${rowType}${pascalCase(index.name)}UpsertResult, ${rowType}${pascalCase(index.name)}UpsertResult, SchemaCollections>({`,
      )
      lines.push("  kind: 'mutation',")
      lines.push(`  name: '${tableName}.upsertBy.${index.name}',`)
      lines.push('  lockTargets(args) {')
      lines.push(
        `    return [createUniqueLockTarget('${tableName}', '${index.name}', args.values as Record<string, unknown>)]`,
      )
      lines.push('  },')
      lines.push('  async applyLocal(context, args) {')
      lines.push(`    const currentRows = readLocalRowsForTable<${rowType}>(context.collections, '${tableName}')`)
      lines.push(
        `    const existingRow = currentRows.find((row) => rowMatchesWhere(row, ${renderWhereFromValues('args.values')}))`,
      )
      lines.push('    if (existingRow) {')
      lines.push(`      const nextRow = { ...existingRow, ...args.update } as ${rowType}`)
      lines.push(
        `      context.transaction.mutate(() => { context.collections.${tableName}.update(getRowKey(SYNC_METADATA.tables.${tableName}, existingRow) as any, (draft) => { Object.assign(draft, args.update) }) })`,
      )
      lines.push("      return { row: nextRow, mode: 'updated' as const }")
      lines.push('    }')
      lines.push(
        `    context.transaction.mutate(() => { context.collections.${tableName}.insert(args.create as any) })`,
      )
      lines.push("    return { row: args.create, mode: 'inserted' as const }")
      lines.push('  },')
      lines.push('  async runServer(context, args) {')
      lines.push(`    const policy = context.policies['${tableName}']`)
      lines.push(`    const existingRow = await context.adapter.getRowByLookup('${tableName}', args.values as Record<string, unknown>)`)
      lines.push(`    const policyContext = { auth: context.auth, args, existingRow, force: context.force, tableName: '${tableName}', operationName: '${tableName}.upsertBy.${index.name}', action: 'upsertBy' as const, indexName: '${index.name}' }`)
      lines.push('    if (existingRow) {')
      lines.push(`      const changes = await runMutationPolicyInputPhases(policy, policyContext, args.update as unknown as Record<string, unknown>)`)
      lines.push(`      await runMutationPolicyExistingPhases(policy, policyContext)`)
      lines.push(`      await validateReferenceColumns(context.adapter, context.metadata, '${tableName}', { ...existingRow, ...changes })`)
      lines.push(`      const row = await context.adapter.updateRow('${tableName}', getRowKey(SYNC_METADATA.tables.${tableName}, existingRow), changes, SYNC_METADATA.tables.${tableName}.keyColumns)`)
      lines.push(`      const result = { row: row as ${rowType}, mode: 'updated' as const }`)
      lines.push(`      await runPolicyAfterCommit(policy, policyContext, result)`)
      lines.push('      return result')
      lines.push('    }')
      lines.push(`    const createInput = await runMutationPolicyInputPhases(policy, policyContext, args.create as unknown as Record<string, unknown>)`)
      lines.push(`    await validateReferenceColumns(context.adapter, context.metadata, '${tableName}', createInput)`)
      lines.push(`    const row = await context.adapter.insertRow('${tableName}', createInput)`)
      lines.push(`    const result = { row: row as ${rowType}, mode: 'inserted' as const }`)
      lines.push(`    await runPolicyAfterCommit(policy, policyContext, result)`)
      lines.push('    return result')
      lines.push('  },')
      lines.push('  resultsEqual(localResult, serverResult) {')
      lines.push('    return syncValuesEqual(localResult, serverResult)')
      lines.push('  },')
      lines.push('  invalidate(_args, result) {')
      lines.push(`    return [{ tableName: '${tableName}', keys: [getRowKey(SYNC_METADATA.tables.${tableName}, result.row)] }]`)
      lines.push('  },')
      lines.push('})')
      lines.push('')
    }
  }

  lines.push(`const __policyModules = [${policyImports.map((entry) => entry.localName).join(', ')}] as Array<Record<string, unknown>>`)
  lines.push(`const __queryModules = [${queryImports.map((entry) => entry.localName).join(', ')}] as Array<Record<string, unknown>>`)
  lines.push(`const __mutationModules = [${mutationImports.map((entry) => entry.localName).join(', ')}] as Array<Record<string, unknown>>`)
  lines.push('')
  lines.push('export const generatedQueries = {')
  for (const def of options.definitions) {
    lines.push(`  ['${def.tableName}.list']: ${camelCase(def.tableName)}ListQuery,`)
    lines.push(`  ['${def.tableName}.get']: ${camelCase(def.tableName)}GetQuery,`)
    for (const index of getGeneratedIndexes(def)) {
      if (index.name === 'by_id' || index.name === 'by_creation_time') {
        continue
      }

      if (index.unique) {
        lines.push(`  ['${def.tableName}.getBy.${index.name}']: ${camelCase(def.tableName)}GetBy${pascalCase(index.name)}Query,`)
      } else {
        lines.push(`  ['${def.tableName}.listBy.${index.name}']: ${camelCase(def.tableName)}ListBy${pascalCase(index.name)}Query,`)
      }
    }
  }
  lines.push('} satisfies Record<string, SyncQueryDefinition<any, any, SchemaCollections>>')
  lines.push('')
  lines.push('export const generatedMutations = {')
  for (const def of options.definitions) {
    lines.push(`  ['${def.tableName}.insert']: ${camelCase(def.tableName)}InsertMutation,`)
    lines.push(`  ['${def.tableName}.update']: ${camelCase(def.tableName)}UpdateMutation,`)
    lines.push(`  ['${def.tableName}.delete']: ${camelCase(def.tableName)}DeleteMutation,`)
    for (const index of getGeneratedIndexes(def).filter((index) => index.unique && index.name !== 'by_id')) {
      lines.push(`  ['${def.tableName}.upsertBy.${index.name}']: ${camelCase(def.tableName)}UpsertBy${pascalCase(index.name)}Mutation,`)
    }
  }
  lines.push('} satisfies Record<string, SyncMutationDefinition<any, any, any, SchemaCollections>>')
  lines.push('')
  lines.push('export const operationRegistry = mergeSyncOperationRegistry({')
  lines.push('  queries: generatedQueries,')
  lines.push('  mutations: generatedMutations,')
  lines.push('  policies: collectDefinedPolicies(__policyModules),')
  lines.push('}, {')
  lines.push('  queries: collectDefinedQueries(__queryModules),')
  lines.push('  mutations: collectDefinedMutations(__mutationModules),')
  lines.push('})')
  lines.push('')
  lines.push('export interface CreateGeneratedSyncClientOptions {')
  lines.push('  database: AsyncSqliteDatabase')
  lines.push('  collections: SchemaCollections')
  lines.push('  createBatchTransaction: CreateSyncBatchTransaction<SchemaCollections>')
  lines.push('  serverBaseUrl: string')
  lines.push('  websocketUrl: string')
  lines.push('  queryPath?: string')
  lines.push('  reconnectDelayMs?: number')
  lines.push('  autoStart?: boolean')
  lines.push('  webSocketFactory?: (url: string) => SyncSocketLike')
  lines.push('}')
  lines.push('')
  lines.push('export function createGeneratedSyncClient(options: CreateGeneratedSyncClientOptions): SyncClient<SchemaCollections> {')
  lines.push('  return createSyncClient({')
  lines.push('    ...options,')
  lines.push('    metadata: SYNC_METADATA,')
  lines.push('    registry: operationRegistry,')
  lines.push('  })')
  lines.push('}')
  lines.push('')
  lines.push('export async function createGeneratedSyncServerRuntime<TAuthContext = unknown>(options: {')
  lines.push('  database: AsyncSqliteDatabase')
  lines.push('  adapter?: import("@sink/lib/server").SyncServerAdapter<TAuthContext>')
  lines.push('  port: number')
  lines.push('  hostname?: string')
  lines.push('  websocketPath?: string')
  lines.push('  queryPath?: string')
  lines.push('  getAuthContext?: (request: import("node:http").IncomingMessage) => Promise<TAuthContext> | TAuthContext')
  lines.push('  handleHttpRequest?: (request: import("node:http").IncomingMessage, response: import("node:http").ServerResponse) => Promise<boolean> | boolean')
  lines.push('  onError?: (error: unknown) => void')
  lines.push('}) {')
  lines.push('  const serverModuleId = "@sink/lib/server"')
  lines.push('  const serverLib = await import(/* @vite-ignore */ serverModuleId)')
  lines.push('  const adapter = options.adapter ?? serverLib.createSqliteSyncServerAdapter<TAuthContext>({')
  lines.push('    database: options.database,')
  lines.push('    metadata: SYNC_METADATA,')
  lines.push('  })')
  lines.push('  return serverLib.createSyncServerRuntime<TAuthContext>({')
  lines.push('    ...options,')
  lines.push('    adapter,')
  lines.push('    registry: operationRegistry,')
  lines.push('    metadata: SYNC_METADATA,')
  lines.push('  })')
  lines.push('}')

  return `${lines.join('\n')}\n`
}

function renderSchemaTypeImports(definitions: TableDefinition[]): string {
  const names = new Set<string>()

  for (const definition of definitions) {
    names.add(rowTypeName(definition.tableName))
    names.add(keyTypeName(definition.tableName))
  }

  return `, ${[...names].sort().join(', ')}`
}

function rowTypeName(tableName: string): string {
  return `${pascalCase(singularTableName(tableName))}Row`
}

function keyTypeName(tableName: string): string {
  return `${pascalCase(singularTableName(tableName))}Key`
}

function singularTableName(tableName: string): string {
  if (tableName.endsWith('ies')) {
    return `${tableName.slice(0, -3)}y`
  }

  if (tableName.endsWith('s')) {
    return tableName.slice(0, -1)
  }

  return tableName
}

function pascalCase(value: string): string {
  return value
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((segment) => segment[0]?.toUpperCase() + segment.slice(1))
    .join('')
}

function camelCase(value: string): string {
  const next = pascalCase(value)
  return next[0]?.toLowerCase() + next.slice(1)
}

function toImportPath(fromFile: string, toFile: string): string {
  const relativePath = path.relative(path.dirname(fromFile), toFile).replaceAll(path.sep, '/')
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`
}

function appendUniqueFields(
  fields: readonly string[],
  trailingFields: readonly string[],
): readonly string[] {
  const next = [...fields]

  for (const field of trailingFields) {
    if (!next.includes(field)) {
      next.push(field)
    }
  }

  return next
}

function getGeneratedIndexes(def: TableDefinition): Array<{
  name: string
  fields: readonly string[]
  filterFields: readonly string[]
  unique: boolean
}> {
  const primaryKeyColumns = getPrimaryKeyColumns(def.options)
  const indexes: Array<{
    name: string
    fields: readonly string[]
    filterFields: readonly string[]
    unique: boolean
  }> = [
    {
      name: 'by_id',
      fields: primaryKeyColumns,
      filterFields: primaryKeyColumns,
      unique: true,
    },
  ]

  if (def.options.withCreatedAt) {
    const fields = appendUniqueFields(['_createdAt'], primaryKeyColumns)
    indexes.push({
      name: 'by_creation_time',
      fields,
      filterFields: [],
      unique: false,
    })
  }

  for (const index of def.indexes) {
    const trailingFields = def.options.withCreatedAt
      ? appendUniqueFields(['_createdAt'], primaryKeyColumns)
      : primaryKeyColumns
    const fields = index.unique
      ? index.fields
      : appendUniqueFields(index.fields, trailingFields)

    indexes.push({
      name: index.name,
      fields,
      filterFields: index.fields,
      unique: index.unique,
    })
  }

  return indexes
}

function getDefaultListIndexName(def: TableDefinition): string {
  const indexNames = new Set(def.indexes.map((index) => index.name))

  if (def.options.withCreatedAt) {
    return 'by_creation_time'
  }

  const firstNonUnique = def.indexes.find((index) => !index.unique)

  if (firstNonUnique) {
    return firstNonUnique.name
  }

  if (indexNames.has('by_name')) {
    return 'by_name'
  }

  return 'by_id'
}

function renderStringTuple(values: readonly string[]): string {
  if (values.length === 0) {
    return '[] as const'
  }

  return `[${values.map((value) => JSON.stringify(value)).join(', ')}] as const`
}

function renderValuesType(
  fields: readonly string[],
  def: TableDefinition,
): string {
  const rowType = rowTypeName(def.tableName)
  const fieldTypes = fields.map((field) => {
    if (field.includes('.')) {
      return `${JSON.stringify(field)}: unknown`
    }

    return `${JSON.stringify(field)}: ${rowType}[${JSON.stringify(field)}]`
  })

  return `{ ${fieldTypes.join('; ')} }`
}

function renderWhereFromValues(source: string): string {
  return `Object.entries(${source} as Record<string, unknown>).map(([column, value]) => ({ column, equals: value }))`
}

function renderOrderBy(fields: readonly string[]): string {
  return `[${fields
    .map((field) => `{ column: ${JSON.stringify(field)}, direction: 'asc' as const }`)
    .join(', ')}]`
}

function renderUpdateChangesType(def: TableDefinition, rowType: string): string {
  const primaryKeyFields = getPrimaryKeyColumns(def.options).map(
    (fieldName) => `'${fieldName}'`,
  )

  return `Partial<Omit<${rowType}, ${primaryKeyFields.join(' | ')}>>`
}
