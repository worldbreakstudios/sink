import { useEffect, useState } from 'react'
import type { SqliteTableColumn } from '@worldbreakstudios/sink-lib'
import {
  ID_AUTOGENERATED,
  type TableName,
} from '@/data/generated/schema.gen'
import { Button } from '@/components/ui/button'
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from '@/components/ui/dialog'
import { Input } from '@/components/ui/input'
import { Label } from '@/components/ui/label'
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from '@/components/ui/select'
import { Textarea } from '@/components/ui/textarea'
import type {
  SqliteDemoCollectionsWorkspace,
  SqliteDemoRow,
  SqliteDemoTableName,
  SqliteInsertDraft,
} from '@/lib/sqlite-demo-collections'
import {
  getSqliteDemoRowKey,
  serializeSqliteDemoKey,
} from '@/lib/sqlite-demo-collections'
import {
  formatReferenceOptionLabel,
  isMultilineColumn,
  isStructuredColumnType,
} from './utils'

export interface InsertModalState {
  tableName: SqliteDemoTableName
  draft: SqliteInsertDraft
  referenceRows: Record<string, SqliteDemoRow[]>
}

export function InsertRowModal({
  modal,
  columns,
  workspace,
  onClose,
  onSubmit,
  onDraftChange,
}: {
  modal: InsertModalState | null
  columns: SqliteTableColumn[]
  workspace: SqliteDemoCollectionsWorkspace | null
  onClose: () => void
  onSubmit: () => Promise<void>
  onDraftChange: (columnName: string, value: string) => void
}) {
  const [validationError, setValidationError] = useState<string | null>(null)
  const [isValidating, setIsValidating] = useState(false)

  useEffect(() => {
    let cancelled = false

    if (!modal || !workspace) {
      setValidationError(null)
      setIsValidating(false)
      return () => {
        cancelled = true
      }
    }

    setIsValidating(true)

    void workspace
      .validateInsertDraft(modal.tableName, modal.draft)
      .then((nextError) => {
        if (!cancelled) {
          setValidationError(nextError)
          setIsValidating(false)
        }
      })
      .catch((error) => {
        if (!cancelled) {
          setValidationError(error instanceof Error ? error.message : String(error))
          setIsValidating(false)
        }
      })

    return () => {
      cancelled = true
    }
  }, [modal, workspace])

  if (!modal || !workspace) {
    return null
  }

  const editableColumns = columns.filter((column) => {
    if (column.name === '_id') {
      return !ID_AUTOGENERATED[modal.tableName]
    }

    return column.pk === 0 && (!column.name.startsWith('_') || column.name === '_actor')
  })

  return (
    <Dialog open={modal !== null} onOpenChange={(open) => !open && onClose()}>
      <DialogContent className="max-h-[calc(100vh-2rem)] max-w-[min(42rem,calc(100vw-2rem))] overflow-y-auto">
        <DialogHeader className="min-w-0 pr-8">
          <DialogTitle>Add row to {modal.tableName}</DialogTitle>
          <DialogDescription>
            This row will be inserted through the generated sync mutation pipeline.
            If the websocket is offline, it will queue locally and replay when the
            connection returns.
          </DialogDescription>
        </DialogHeader>

        <form
          className="min-w-0 space-y-4"
          onSubmit={async (event) => {
            event.preventDefault()
            await onSubmit()
          }}
        >
          <div className="grid min-w-0 gap-4">
            {editableColumns.map((column) => {
              const referenceColumn = workspace.getReferenceColumn(
                modal.tableName,
                column.name,
              )
              const referenceRows = referenceColumn
                ? (modal.referenceRows[column.name] ?? []).filter((row) => {
                    if (!referenceColumn.actorScoped) {
                      return true
                    }

                    const rowRecord = row as unknown as Record<string, unknown>
                    return rowRecord._actor === modal.draft._actor
                  })
                : []

              return (
                <div key={column.name} className="grid min-w-0 gap-2">
                  <Label htmlFor={`insert-${column.name}`}>{column.name}</Label>
                  {referenceColumn ? (
                    <Select
                      value={
                        modal.draft[column.name] !== ''
                          ? modal.draft[column.name]
                          : column.notnull
                            ? undefined
                            : '__empty__'
                      }
                      onValueChange={(nextValue) =>
                        onDraftChange(
                          column.name,
                          nextValue === '__empty__' ? '' : nextValue,
                        )
                      }
                      disabled={referenceRows.length === 0}
                    >
                      <SelectTrigger
                        id={`insert-${column.name}`}
                        className="w-full min-w-0"
                      >
                        <SelectValue
                          placeholder={
                            referenceRows.length === 0
                              ? 'No rows available'
                              : 'Select a row'
                          }
                        />
                      </SelectTrigger>
                      <SelectContent>
                        {!column.notnull && (
                          <SelectItem value="__empty__">(none)</SelectItem>
                        )}
                        {referenceRows.map((row) => (
                          <SelectItem
                            key={serializeSqliteDemoKey(
                              referenceColumn.referencedTable as TableName,
                              getSqliteDemoRowKey(
                                referenceColumn.referencedTable as TableName,
                                row,
                              ),
                            )}
                            value={String(row._id)}
                          >
                            {formatReferenceOptionLabel(
                              referenceColumn.referencedTable as TableName,
                              row,
                            )}
                          </SelectItem>
                        ))}
                      </SelectContent>
                    </Select>
                  ) : isMultilineColumn(column.name) || isStructuredColumnType(column.type) ? (
                    <Textarea
                      id={`insert-${column.name}`}
                      value={modal.draft[column.name] ?? ''}
                      onChange={(event) => onDraftChange(column.name, event.target.value)}
                    />
                  ) : (
                    <Input
                      id={`insert-${column.name}`}
                      value={modal.draft[column.name] ?? ''}
                      onChange={(event) => onDraftChange(column.name, event.target.value)}
                    />
                  )}
                  <p className="text-xs text-muted-foreground">
                    {referenceColumn ? 'ID' : column.type || 'TEXT'}
                    {referenceColumn
                      ? ` • references ${referenceColumn.referencedTable}`
                      : ''}
                    {column.pk ? ' • primary key' : ''}
                    {column.notnull ? ' • required' : ''}
                  </p>
                </div>
              )
            })}
          </div>

          {validationError ? (
            <div className="rounded-md border border-amber-300 bg-amber-50 px-3 py-2 text-sm text-amber-900 dark:border-amber-800 dark:bg-amber-950 dark:text-amber-200">
              {validationError}
            </div>
          ) : null}

          <DialogFooter>
            <Button type="button" variant="outline" onClick={onClose}>
              Cancel
            </Button>
            <Button type="submit" disabled={isValidating || Boolean(validationError)}>
              {isValidating ? 'Checking…' : 'Submit row'}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  )
}
